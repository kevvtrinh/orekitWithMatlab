function report = benchmarkSimpleKinodynamicBiRRTGauntlets( ...
        randomSeeds, maximumIterations)
%BENCHMARKSIMPLEKINODYNAMICBIRRTGAUNTLETS Test only the simple BiRRT.
%
% report = benchmarkSimpleKinodynamicBiRRTGauntlets()
% report = benchmarkSimpleKinodynamicBiRRTGauntlets([2 7 19], 5000)
%
% The benchmark calls planSimpleAzElTimeKinodynamicBiRRT directly on the
% five-turn static spiral, rotating-slot gauntlet, and spinning-rod spiral.
% It does not call Dijkstra, RRT*, or any other planner. Each scenario uses
% its native obstacle sampling interval as the simple planner time step,
% its published safety margin, and the default Cartesian nine-command jerk
% lattice. The added jerk limit equals that scenario's acceleration limit
% per second. Every successful route is rechecked independently at half the
% planner collision-check interval.

if nargin < 1
    randomSeeds = [2 7 19];
end
if nargin < 2
    maximumIterations = 5000;
end
validateattributes(randomSeeds, {'numeric'}, ...
    {'vector', 'integer', 'nonnegative'});
validateattributes(maximumIterations, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
randomSeeds = double(randomSeeds(:));

caseDefinitions = makeBenchmarkCases();
runCount = numel(caseDefinitions) * numel(randomSeeds);
scenario = strings(runCount, 1);
seed = nan(runCount, 1);
success = false(runCount, 1);
elapsed_s = nan(runCount, 1);
iterations = nan(runCount, 1);
generatedNodes = nan(runCount, 1);
generatedCandidates = nan(runCount, 1);
rejectedCandidates = nan(runCount, 1);
initialTreeMaxTime_s = nan(runCount, 1);
destinationTreeMinTime_s = nan(runCount, 1);
treeTimeGap_s = nan(runCount, 1);
pathLength_deg = nan(runCount, 1);
plannerCollisionValidated = false(runCount, 1);
fineCollisionValidated = false(runCount, 1);
forwardDynamicsValidated = false(runCount, 1);
windingTurns = nan(runCount, 1);
inwardRingCrossings = nan(runCount, 1);
message = strings(runCount, 1);
plans = cell(runCount, 1);

row = 0;
for caseIndex = 1:numel(caseDefinitions)
    definition = caseDefinitions(caseIndex);
    for seedIndex = 1:numel(randomSeeds)
        row = row + 1;
        scenario(row) = definition.Name;
        seed(row) = randomSeeds(seedIndex);
        options = simpleOptions(definition, randomSeeds(seedIndex), ...
            maximumIterations);
        limits = definition.Problem.limits;
        limits.maxJerk_deg_s3 = limits.maxAcceleration_deg_s2;

        runTimer = tic;
        try
            plan = planSimpleAzElTimeKinodynamicBiRRT( ...
                definition.Problem.azElData, ...
                definition.Problem.startState, ...
                definition.Problem.stopState, limits, options);
            elapsed_s(row) = toc(runTimer);
            plans{row} = plan;
            success(row) = plan.success;
            iterations(row) = plan.iterationCount;
            generatedNodes(row) = plan.generatedNodeCount;
            generatedCandidates(row) = plan.generatedCandidateCount;
            rejectedCandidates(row) = plan.rejectedNodeCount;
            initialTreeMaxTime_s(row) = max(plan.initialTree.State(:, 1));
            destinationTreeMinTime_s(row) = min( ...
                plan.destinationTree.State(:, 1));
            treeTimeGap_s(row) = destinationTreeMinTime_s(row) - ...
                initialTreeMaxTime_s(row);
            plannerCollisionValidated(row) = ...
                plan.exactCollisionValidated;
            forwardDynamicsValidated(row) = ...
                plan.forwardDynamicsValidated;
            message(row) = plan.message;
            if plan.success
                pathLength_deg(row) = plan.totalCost;
                fineCollisionValidated(row) = ...
                    independentlyValidateCollision(plan, ...
                    definition.FineValidationStep_s);
                radialDistance_deg = hypot( ...
                    plan.positionUnwrapped_deg(:, 1), ...
                    plan.positionUnwrapped_deg(:, 2));
                if definition.Diagnostic == "winding"
                    validPolarSample = radialDistance_deg >= ...
                        definition.MinimumPolarRadius_deg;
                    polarAngle_rad = unwrap(atan2( ...
                        plan.positionUnwrapped_deg(validPolarSample, 2), ...
                        plan.positionUnwrapped_deg(validPolarSample, 1)));
                    if numel(polarAngle_rad) >= 2
                        windingTurns(row) = abs(polarAngle_rad(end) - ...
                            polarAngle_rad(1)) / (2 * pi);
                    end
                elseif definition.Diagnostic == "rings"
                    inwardRingCrossings(row) = countInwardRingCrossings( ...
                        radialDistance_deg, ...
                        definition.RingMidRadius_deg);
                end
            end
        catch exception
            elapsed_s(row) = toc(runTimer);
            message(row) = string(exception.identifier) + ": " + ...
                string(exception.message);
        end
        fprintf("  %-28s seed %3d: success=%d, %.2f s, %s\n", ...
            scenario(row), seed(row), success(row), elapsed_s(row), ...
            message(row));
    end
end

results = table(scenario, seed, success, elapsed_s, iterations, ...
    generatedNodes, generatedCandidates, rejectedCandidates, ...
    initialTreeMaxTime_s, destinationTreeMinTime_s, treeTimeGap_s, ...
    pathLength_deg, ...
    plannerCollisionValidated, fineCollisionValidated, ...
    forwardDynamicsValidated, windingTurns, inwardRingCrossings, message);
disp(results);
report = struct( ...
    "planner", "planSimpleAzElTimeKinodynamicBiRRT", ...
    "randomSeeds", randomSeeds, ...
    "maximumIterations", maximumIterations, ...
    "caseDefinitions", caseDefinitions, ...
    "results", results, ...
    "plans", {plans});
end


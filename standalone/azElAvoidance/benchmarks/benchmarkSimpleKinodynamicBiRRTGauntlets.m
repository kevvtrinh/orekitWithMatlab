function options = simpleOptions(definition, randomSeed, maximumIterations)
options = struct( ...
    "TimeStep_s", definition.TimeStep_s, ...
    "CollisionCheckStep_s", definition.CollisionCheckStep_s, ...
    "DestinationSampleProbability", 0.20, ...
    "AllowAzimuthWrap", false, ...
    "MaximumIterations", maximumIterations, ...
    "MaximumTreeNodes", ceil(maximumIterations / 2) + 2, ...
    "RandomSeed", randomSeed, ...
    "CollisionQueryOptions", struct( ...
    "SafetyMarginDeg", definition.Problem.options.SafetyMargin_deg, ...
    "TimePaddingSamples", definition.TimePaddingSamples), ...
    "MaximumObstacleVerticesPerRegion", 500);
end

function isCollisionFree = independentlyValidateCollision(plan, step_s)
sampledTime_s = zeros(0, 1);
sampledPosition_deg = zeros(0, 2);
for edgeIndex = 1:numel(plan.time_s) - 1
    duration_s = plan.time_s(edgeIndex + 1) - plan.time_s(edgeIndex);
    intervalCount = max(1, ceil(duration_s / step_s));
    elapsed_s = linspace(0, duration_s, intervalCount + 1).';
    if edgeIndex > 1
        elapsed_s(1) = [];
    end
    jerk_deg_s3 = plan.jerk_deg_s3(edgeIndex + 1, :);
    sampledTime_s = [sampledTime_s; ...
        plan.time_s(edgeIndex) + elapsed_s]; %#ok<AGROW>
    sampledPosition_deg = [sampledPosition_deg; ...
        plan.position_deg(edgeIndex, :) + ...
        elapsed_s .* plan.velocity_deg_s(edgeIndex, :) + ...
        0.5 * elapsed_s.^2 .* ...
        plan.acceleration_deg_s2(edgeIndex, :) + ...
        (1 / 6) * elapsed_s.^3 .* jerk_deg_s3]; %#ok<AGROW>
end
occupied = queryAzElTimeObstacle(plan.workspace, ...
    sampledPosition_deg(:, 1), sampledPosition_deg(:, 2), ...
    sampledTime_s, plan.options.CollisionQueryOptions);
isCollisionFree = ~any(occupied);
end

function crossingCount = countInwardRingCrossings(radius_deg, midRadius_deg)
crossingCount = 0;
for ringIndex = 1:numel(midRadius_deg)
    crossingCount = crossingCount + any( ...
        radius_deg(1:end - 1) > midRadius_deg(ringIndex) & ...
        radius_deg(2:end) <= midRadius_deg(ringIndex));
end
end

function problem = makeFiveTurnSpiral()
time_s = (0:0.5:400).';
[wallAzimuth_deg, wallElevation_deg] = spiralWall( ...
    5, 2, 3, 0.4, 241);
problem = struct( ...
    "azElData", makeAzElObstacleData( ...
    "Five-turn spiral wall", time_s, ...
    wallAzimuth_deg, wallElevation_deg), ...
    "startState", boundaryState(0, [18, 1.5]), ...
    "stopState", boundaryState(400, [0, 0]), ...
    "limits", struct( ...
    "azimuth_deg", [-20, 20], ...
    "elevation_deg", [-20, 20], ...
    "maxVelocity_deg_s", [3, 3], ...
    "maxAcceleration_deg_s2", [3, 3]), ...
    "options", struct("SafetyMargin_deg", 0.5));
end

function [azimuth_deg, elevation_deg] = spiralWall( ...
        turnCount, innerRadius, turnSpacing, halfWidth, sampleCount)
theta = linspace(0, 2 * pi * turnCount, sampleCount).';
radius = innerRadius + turnSpacing * theta / (2 * pi);
centerAzimuth = radius .* cos(theta);
centerElevation = radius .* sin(theta);
deltaAzimuth = gradient(centerAzimuth);
deltaElevation = gradient(centerElevation);
tangentMagnitude = hypot(deltaAzimuth, deltaElevation);
normalAzimuth = -deltaElevation ./ tangentMagnitude;
normalElevation = deltaAzimuth ./ tangentMagnitude;
leftAzimuth = centerAzimuth + halfWidth * normalAzimuth;
leftElevation = centerElevation + halfWidth * normalElevation;
rightAzimuth = centerAzimuth - halfWidth * normalAzimuth;
rightElevation = centerElevation - halfWidth * normalElevation;
azimuth_deg = [leftAzimuth; flipud(rightAzimuth); leftAzimuth(1)];
elevation_deg = [ ...
    leftElevation; flipud(rightElevation); leftElevation(1)];
end

function state = boundaryState(time_s, position_deg)
state = struct( ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
end

function report = benchmarkAdaptiveMeshKinodynamicAStar(options)
%BENCHMARKADAPTIVEMESHKINODYNAMICASTAR Test adaptive collision occupancy.
%
% report = benchmarkAdaptiveMeshKinodynamicAStar()
% report = benchmarkAdaptiveMeshKinodynamicAStar(options)
%
% The benchmark runs examples 02-13 with their existing planner, then runs
% unweighted kinodynamic A* on the same finite kinematic lattice while
% using AdaptiveAzElTimeMesh for primitive collision checks. Every returned
% path is densely replayed against the original packed polygons.
%
% Example 01 is omitted because it intentionally requires caller-supplied
% azElData. Example 13 uses a fixed seed for reproducibility and fixes the
% moving endpoint at the interception selected by the baseline planner.
%
% Options:
%   CaseNumbers             Default 2:13.
%   PerCaseWallTime_s       Adaptive A* cap, default 15.
%   MaxExpansions           Default 300000.
%   MaximumTimeSamples      Adaptive mesh cap, default 201.
%   MaximumLeafCells        Default 100000.
%   InitialToMinimumRatio   Initial/minimum cell ratio, default 8.
%   ValidationStep_s        Exact replay step, default 0.1.
%   OccupancySampleCount    Mesh/polygon comparison count, default 5000.
%   RandomSeed              Example 13 seed, default 1478112231.
%   RunBaseline             Default true.
%   BaselinePlans           Optional struct keyed as Case02, Case03, ...
%   SavePath                Optional MAT output path, default "".

if nargin < 1
    options = struct();
end
options = normalizeOptions(options);
caseNumbers = reshape(options.CaseNumbers, 1, []);
rows = repmat(emptyRow(), numel(caseNumbers), 1);
details = cell(numel(caseNumbers), 1);

oldVisibility = get(groot, "DefaultFigureVisible");
set(groot, "DefaultFigureVisible", "off");
visibilityCleanup = onCleanup( ...
    @() set(groot, "DefaultFigureVisible", oldVisibility));

for caseIndex = 1:numel(caseNumbers)
    caseNumber = caseNumbers(caseIndex);
    fprintf("\n=== Adaptive kinodynamic benchmark: example %02d ===\n", ...
        caseNumber);
    row = emptyRow();
    row.CaseNumber = caseNumber;
    row.Example = "example" + compose("%02d", caseNumber);
    try
        baseline = obtainBaseline(caseNumber, options);
        close all force;
        row.Example = baseline.Name;
        row.BaselineSuccess = baseline.Plan.success;
        row.BaselineSearch_s = fieldOr( ...
            baseline.Plan, "searchElapsed_s", NaN);
        row.BaselineLength_deg = fieldOr( ...
            baseline.Plan, "angularPathLength_deg", NaN);
        if ~baseline.Plan.success
            row.Status = "BASELINE_FAILED";
            row.Message = string(baseline.Plan.message);
            rows(caseIndex) = row;
            continue;
        end

        [mesh, meshSeconds, meshRefinements] = ...
            makeMesh(baseline.Plan, options);
        row.MeshBuild_s = meshSeconds;
        row.MeshLeaves = mesh.LeafCount;
        row.MeshRefinementCount = meshRefinements;
        row.MeshCompression = ...
            mesh.Stats.DenseMinimumGridVoxelEstimate / ...
            max(1, mesh.Stats.AdaptiveCellTimeSamples);
        row.MeshUnresolvedSamples = ...
            mesh.Stats.UnresolvedCellTimeSamples;
        occupancyAccuracy = measureOccupancyAccuracy( ...
            mesh, baseline.Plan.workspace, baseline.Plan, ...
            options.OccupancySampleCount);
        row.OccupancyAccuracy = occupancyAccuracy.Accuracy;
        row.FalseNegativeRate = occupancyAccuracy.FalseNegativeRate;
        row.FalsePositiveRate = occupancyAccuracy.FalsePositiveRate;

        [search, searchSeconds, internal] = runAdaptiveSearch( ...
            mesh, baseline.Plan, options);
        row.Search_s = searchSeconds;
        row.SearchSuccess = search.Success;
        row.ExpandedNodes = search.ExpandedNodeCount;
        row.GeneratedNodes = search.GeneratedNodeCount;
        row.Message = string(search.Message);
        if ~search.Success
            row.Status = classifyFailure(search.Message);
            rows(caseIndex) = row;
            details{caseIndex} = struct( ...
                "Baseline", baseline, "Mesh", mesh, ...
                "Search", search, "Internal", internal, ...
                "OccupancyAccuracy", occupancyAccuracy);
            fprintf("%s: %s in %.2f s (%d expanded).\n", ...
                row.Example, row.Status, row.Search_s, ...
                row.ExpandedNodes);
            continue;
        end

        validation = validateSearch( ...
            search, baseline.Plan.workspace, baseline.Plan, ...
            options.ValidationStep_s);
        row.ExactCollisionCount = validation.CollisionCount;
        row.ExactValid = validation.CollisionCount == 0;
        row.GoalError_deg = validation.GoalErrorDeg;
        row.PathLength_deg = validation.AngularPathLengthDeg;
        row.PathLengthRatio = row.PathLength_deg / ...
            max(row.BaselineLength_deg, eps);
        row.ArrivalTime_s = validation.ArrivalTime_s;
        if row.ExactValid
            row.Status = "PASS";
        else
            row.Status = "EXACT_COLLISION";
        end
        rows(caseIndex) = row;
        details{caseIndex} = struct( ...
            "Baseline", baseline, "Mesh", mesh, ...
            "Search", search, "Internal", internal, ...
            "Validation", validation, ...
            "OccupancyAccuracy", occupancyAccuracy);
        fprintf([ ...
            '%s: %s, mesh %.2f s, A* %.2f s, %d expanded, ' ...
            '%.3f deg (%.2fx baseline), %d exact collisions.\n'], ...
            char(row.Example), char(row.Status), ...
            row.MeshBuild_s, row.Search_s, ...
            row.ExpandedNodes, row.PathLength_deg, ...
            row.PathLengthRatio, row.ExactCollisionCount);
    catch exception
        close all force;
        row.Status = "ERROR";
        row.Message = string(exception.message);
        rows(caseIndex) = row;
        details{caseIndex} = struct("Exception", exception);
        fprintf("%s: ERROR: %s\n", row.Example, exception.message);
    end
end
clear visibilityCleanup;

summary = struct2table(rows);
report = struct( ...
    "Format", "AdaptiveMeshKinodynamicBenchmark", ...
    "Version", 1, ...
    "GeneratedAt", datetime("now", "TimeZone", "UTC"), ...
    "Options", options, ...
    "Summary", summary, ...
    "Details", {details});
displayNames = cellstr([ ...
    "CaseNumber", "Example", "Status", "MeshBuild_s", "Search_s", ...
    "MeshLeaves", "ExpandedNodes", "ExactValid", ...
    "PathLengthRatio"]);
disp(summary(:, displayNames));
if strlength(options.SavePath) > 0
    save(options.SavePath, "report", "-v7.3");
end
end

function baseline = obtainBaseline(caseNumber, options)
fieldName = "Case" + compose("%02d", caseNumber);
if isfield(options.BaselinePlans, fieldName)
    cached = options.BaselinePlans.(fieldName);
    if isstruct(cached) && isscalar(cached) && ...
            isfield(cached, "Plan")
        baseline = cached;
    else
        baseline = struct("Name", fieldName, "Plan", cached);
    end
    return;
end
if ~options.RunBaseline
    error("benchmarkAdaptiveMeshKinodynamicAStar:MissingBaseline", ...
        "No cached baseline was provided for example %02d.", caseNumber);
end
switch caseNumber
    case 2
        output = example02VietnamChinaAvoidance();
        plan = output;
        name = "02 Vietnam + China";
    case 3
        [output, ~] = example03KinodynamicDetour();
        plan = output;
        name = "03 Kinodynamic detour";
    case 4
        output = example04DynamicSafeIntervals();
        plan = output.plan;
        name = "04 Moving walls";
    case 5
        output = example05FiveTurnSpiral();
        plan = output.plan;
        name = "05 Five-turn spiral";
    case 6
        output = example06StopGoGates();
        plan = output.plan;
        name = "06 Stop-go gates";
    case 7
        output = example07WrappedAzimuthSeam();
        plan = output.plan;
        name = "07 Wrapped seam";
    case 8
        output = example08AlternatingSlalom();
        plan = output.plan;
        name = "08 Alternating slalom";
    case 9
        output = example09UTrapEscape();
        plan = output.plan;
        name = "09 U-trap";
    case 10
        output = example10RotatingSlots(struct("PauseSeconds", 0));
        plan = output.plan;
        name = "10 Rotating slots";
    case 11
        output = example11ChasedBoresight(struct("PauseSeconds", 0));
        plan = output.plan;
        name = "11 Chased boresight";
    case 12
        output = example12SynchronizedWindmills( ...
            struct("PauseSeconds", 0));
        plan = output.plan;
        name = "12 Windmills";
    case 13
        output = example13RandomBlinkingIntercept( ...
            options.RandomSeed, struct("PauseSeconds", 0));
        plan = output.plan;
        name = "13 Blinking intercept";
    otherwise
        error("benchmarkAdaptiveMeshKinodynamicAStar:UnsupportedCase", ...
            "Only examples 02-13 have built-in benchmark data.");
end
baseline = struct("Name", name, "Plan", plan);
end

function [mesh, elapsed, refinementCount] = makeMesh(plan, options)
limits = plan.limits;
gridSpec = struct( ...
    "AzimuthLimitsDeg", limits.azimuth_deg, ...
    "ElevationLimitsDeg", limits.elevation_deg, ...
    "TimeLimitsSeconds", [ ...
    plan.startState.time_s, plan.stopState.time_s]);
minimumSize = meshMinimumSize(plan);
initialSize = min( ...
    options.InitialToMinimumRatio .* minimumSize, ...
    [diff(limits.azimuth_deg), diff(limits.elevation_deg)]);
initialSize = max(initialSize, 2 .* minimumSize);
isStatic = workspaceIsStatic( ...
    plan.workspace, plan.startState.time_s, plan.stopState.time_s);
meshOptions = struct( ...
    "InitialCellSizeDeg", initialSize, ...
    "MinimumCellSizeDeg", minimumSize, ...
    "MaximumTimeSamples", options.MaximumTimeSamples, ...
    "SafetyMarginDeg", fieldOr(plan.options, ...
    "SafetyMargin_deg", 0), ...
    "TimePaddingSamples", 1, ...
    "MaximumLeafCells", options.MaximumLeafCells, ...
    "AllowAzimuthWrap", fieldOr(plan.options, ...
    "AllowAzimuthWrap", false));
if isStatic
    meshOptions.TimeSeconds = [ ...
        plan.startState.time_s; plan.stopState.time_s];
end
timer = tic;
refinementCount = 0;
minimumFloor = max(minimumSize ./ 4, 0.125);
while true
    mesh = buildAdaptiveAzElTimeMesh( ...
        plan.workspace, gridSpec, meshOptions);
    [startBlocked, ~] = queryAdaptiveAzElTimeMesh(mesh, ...
        plan.startState.position_deg(1), ...
        plan.startState.position_deg(2), ...
        plan.startState.time_s);
    [goalBlocked, ~] = queryAdaptiveAzElTimeMesh(mesh, ...
        plan.stopState.position_deg(1), ...
        plan.stopState.position_deg(2), ...
        plan.stopState.time_s);
    exactEndpointBlocked = queryAzElTimeObstacle( ...
        plan.workspace, ...
        [plan.startState.position_deg(1), ...
        plan.stopState.position_deg(1)], ...
        [plan.startState.position_deg(2), ...
        plan.stopState.position_deg(2)], ...
        [plan.startState.time_s, plan.stopState.time_s], struct( ...
        "SafetyMarginDeg", fieldOr(plan.options, ...
        "SafetyMargin_deg", 0), ...
        "TimePaddingSamples", 1));
    needsEndpointRefinement = ...
        (startBlocked && ~exactEndpointBlocked(1)) || ...
        (goalBlocked && ~exactEndpointBlocked(2));
    if ~needsEndpointRefinement || ...
            all(meshOptions.MinimumCellSizeDeg <= ...
            minimumFloor .* (1 + 1e-10))
        break;
    end
    meshOptions.MinimumCellSizeDeg = max( ...
        meshOptions.MinimumCellSizeDeg ./ 2, minimumFloor);
    refinementCount = refinementCount + 1;
end
elapsed = toc(timer);
end

function minimumSize = meshMinimumSize(plan)
guideStep = fieldOr(plan.options, "GridStep_deg", 1);
if isscalar(guideStep)
    guideStep = [guideStep guideStep];
end

minimumSize = min(max(double(guideStep(:).'), 0.25), 1);
span = [diff(plan.limits.azimuth_deg), ...
    diff(plan.limits.elevation_deg)];
minimumSize = min(minimumSize, span ./ 4);
end

function yes = workspaceIsStatic(workspace, startTime_s, stopTime_s)
yes = true;
for obstacle = reshape(workspace.Obstacles, 1, [])
    if obstacle.SampleCount == 0
        continue;
    end
    if obstacle.TimeSeconds(1) > startTime_s + 1e-9 || ...
            obstacle.TimeSeconds(end) < stopTime_s - 1e-9
        yes = false;
        return;
    end
    count = double(diff(obstacle.SliceOffsets));
    if any(count ~= count(1))
        yes = false;
        return;
    end
    firstIndex = double(obstacle.SliceOffsets(1)): ...
        double(obstacle.SliceOffsets(2) - 1);
    firstAzimuth = obstacle.AzimuthDeg(firstIndex);
    firstElevation = obstacle.ElevationDeg(firstIndex);
    for sample = 2:obstacle.SampleCount
        index = double(obstacle.SliceOffsets(sample)): ...
            double(obstacle.SliceOffsets(sample + 1) - 1);
        if ~isequaln(obstacle.AzimuthDeg(index), firstAzimuth) || ...
                ~isequaln(obstacle.ElevationDeg(index), firstElevation)
            yes = false;
            return;
        end
    end
end
end

function [search, elapsed, internal] = runAdaptiveSearch( ...
        mesh, plan, options)
duration = plan.stopState.time_s - plan.startState.time_s;
dt = fieldOr(plan.options, "KinodynamicTimeStep_s", ...
    min(1, max(0.5, fieldOr(plan.options, "SampleTime_s", 1))));
dt = min(dt, duration);
activeAcceleration = min( ...
    plan.limits.maxAcceleration_deg_s2, ...
    plan.limits.maxVelocity_deg_s ./ dt);
internalLimits = struct( ...
    "AzimuthLimitsDeg", plan.limits.azimuth_deg, ...
    "ElevationLimitsDeg", plan.limits.elevation_deg, ...
    "AzimuthRateLimitDegPerSec", ...
    plan.limits.maxVelocity_deg_s(1), ...
    "ElevationRateLimitDegPerSec", ...
    plan.limits.maxVelocity_deg_s(2), ...
    "AzimuthAccelerationLimitDegPerSec2", ...
    activeAcceleration(1), ...
    "ElevationAccelerationLimitDegPerSec2", ...
    activeAcceleration(2));
start = struct( ...
    "AzimuthDeg", plan.startState.position_deg(1), ...
    "ElevationDeg", plan.startState.position_deg(2), ...
    "AzimuthRateDegPerSec", plan.startState.velocity_deg_s(1), ...
    "ElevationRateDegPerSec", plan.startState.velocity_deg_s(2), ...
    "AzimuthAccelerationDegPerSec2", ...
    plan.startState.acceleration_deg_s2(1), ...
    "ElevationAccelerationDegPerSec2", ...
    plan.startState.acceleration_deg_s2(2), ...
    "Time", plan.startState.time_s);
goal = struct( ...
    "AzimuthDeg", plan.stopState.position_deg(1), ...
    "ElevationDeg", plan.stopState.position_deg(2), ...
    "AzimuthRateDegPerSec", plan.stopState.velocity_deg_s(1), ...
    "ElevationRateDegPerSec", plan.stopState.velocity_deg_s(2), ...
    "EarliestTime", plan.startState.time_s, ...
    "LatestTime", plan.stopState.time_s);
searchOptions = struct( ...
    "TimeStepSeconds", dt, ...
    "MaxPlanningTimeSeconds", duration, ...
    "Objective", fieldOr(plan.options, ...
    "Objective", "minimumAngularDistance"), ...
    "HeuristicWeight", 1, ...
    "AzimuthWrap", fieldOr(plan.options, ...
    "AllowAzimuthWrap", false), ...
    "CollisionCheckStepSeconds", min(dt / 4, ...
    options.ValidationStep_s), ...
    "TimePaddingSamples", 0, ...
    "SafetyMarginDeg", 0, ...
    "MaxExpansions", options.MaxExpansions, ...
    "MaxWallTimeSeconds", options.PerCaseWallTime_s);
timer = tic;
search = planAzElKinodynamicAStar( ...
    mesh, start, goal, internalLimits, searchOptions);
elapsed = toc(timer);
internal = struct( ...
    "Limits", internalLimits, ...
    "Options", searchOptions, ...
    "Start", start, ...
    "Goal", goal);
end

function result = measureOccupancyAccuracy( ...
        mesh, workspace, plan, maximumSamples)
leafCount = numel(mesh.Leaves);
timeCount = numel(mesh.TimeSeconds);
total = leafCount * timeCount;
sampleCount = min(total, maximumSamples);
linear = unique(round(linspace(1, total, sampleCount))).';
leafIndex = mod(linear - 1, leafCount) + 1;
timeIndex = floor((linear - 1) / leafCount) + 1;
center = vertcat(mesh.Leaves(leafIndex).CenterDeg);
predicted = false(numel(linear), 1);
for k = 1:numel(linear)
    predicted(k) = ~mesh.Leaves(leafIndex(k)).FreeByTime(timeIndex(k));
end
exact = queryAzElTimeObstacle(workspace, ...
    center(:, 1), center(:, 2), mesh.TimeSeconds(timeIndex), struct( ...
    "SafetyMarginDeg", fieldOr(plan.options, ...
    "SafetyMargin_deg", 0), ...
    "TimePaddingSamples", 1));
falseNegative = ~predicted & exact;
falsePositive = predicted & ~exact;
result = struct( ...
    "SampleCount", numel(linear), ...
    "Accuracy", mean(predicted == exact), ...
    "FalseNegativeCount", nnz(falseNegative), ...
    "FalsePositiveCount", nnz(falsePositive), ...
    "FalseNegativeRate", ...
    nnz(falseNegative) / max(1, nnz(exact)), ...
    "FalsePositiveRate", ...
    nnz(falsePositive) / max(1, nnz(~exact)));
end

function validation = validateSearch(search, workspace, plan, step)
path = search.Path;
timeParts = cell(max(1, height(path) - 1), 1);
positionParts = cell(size(timeParts));
for edge = 1:height(path) - 1
    duration = path.ElapsedSeconds(edge + 1) - ...
        path.ElapsedSeconds(edge);
    sampleCount = max(2, ceil(duration / step) + 1);
    tau = linspace(0, duration, sampleCount).';
    if edge < height(path) - 1
        tau(end) = [];
    end
    acceleration = [ ...
        path.AzimuthAccelerationDegPerSec2(edge + 1), ...
        path.ElevationAccelerationDegPerSec2(edge + 1)];
    rate = [ ...
        path.AzimuthRateDegPerSec(edge), ...
        path.ElevationRateDegPerSec(edge)];
    position = [ ...
        path.AzimuthUnwrappedDeg(edge), ...
        path.ElevationDeg(edge)] + ...
        tau .* rate + 0.5 * tau.^2 .* acceleration;
    if fieldOr(plan.options, "AllowAzimuthWrap", false)
        lower = plan.limits.azimuth_deg(1);
        span = diff(plan.limits.azimuth_deg);
        position(:, 1) = mod(position(:, 1) - lower, span) + lower;
    end
    timeParts{edge} = ...
        path.TimeSecondsFromReference(edge) + tau;
    positionParts{edge} = position;
end
if height(path) == 1
    time_s = path.TimeSecondsFromReference;
    position = [path.AzimuthDeg path.ElevationDeg];
else
    time_s = vertcat(timeParts{:});
    position = vertcat(positionParts{:});
end
blocked = queryAzElTimeObstacle(workspace, ...
    position(:, 1), position(:, 2), time_s, struct( ...
    "SafetyMarginDeg", fieldOr(plan.options, ...
    "SafetyMargin_deg", 0), ...
    "TimePaddingSamples", 1));
delta = diff(position, 1, 1);
if fieldOr(plan.options, "AllowAzimuthWrap", false)
    span = diff(plan.limits.azimuth_deg);
    delta(:, 1) = mod(delta(:, 1) + span / 2, span) - span / 2;
end
goalDelta = position(end, :) - plan.stopState.position_deg;
if fieldOr(plan.options, "AllowAzimuthWrap", false)
    span = diff(plan.limits.azimuth_deg);
    goalDelta(1) = mod(goalDelta(1) + span / 2, span) - span / 2;
end
validation = struct( ...
    "Time_s", time_s, ...
    "Position_deg", position, ...
    "Blocked", blocked, ...
    "CollisionCount", nnz(blocked), ...
    "GoalErrorDeg", hypot(goalDelta(1), goalDelta(2)), ...
    "AngularPathLengthDeg", sum(hypot(delta(:, 1), delta(:, 2))), ...
    "ArrivalTime_s", time_s(end));
end

function status = classifyFailure(message)
message = lower(string(message));
if contains(message, "walltimeseconds")
    status = "TIMEOUT";
elseif contains(message, "maxexpansions")
    status = "EXPANSION_LIMIT";
else
    status = "NO_PATH";
end
end

function options = normalizeOptions(options)
defaults = struct( ...
    "CaseNumbers", 2:13, ...
    "PerCaseWallTime_s", 15, ...
    "MaxExpansions", 300000, ...
    "MaximumTimeSamples", 201, ...
    "MaximumLeafCells", 100000, ...
    "InitialToMinimumRatio", 8, ...
    "ValidationStep_s", 0.1, ...
    "OccupancySampleCount", 5000, ...
    "RandomSeed", 1478112231, ...
    "RunBaseline", true, ...
    "BaselinePlans", struct(), ...
    "SavePath", "");
options = applyDefaults(options, defaults);
validateattributes(options.CaseNumbers, {'numeric'}, ...
    {'vector', 'integer', '>=', 2, '<=', 13});
validateattributes(options.PerCaseWallTime_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(options.MaxExpansions, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(options.MaximumTimeSamples, {'numeric'}, ...
    {'scalar', 'integer', '>=', 2});
validateattributes(options.MaximumLeafCells, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(options.InitialToMinimumRatio, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>', 1});
validateattributes(options.ValidationStep_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(options.OccupancySampleCount, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(options.RandomSeed, {'numeric'}, ...
    {'scalar', 'integer', 'positive', '<=', intmax("int32")});
validateattributes(options.RunBaseline, {'logical', 'numeric'}, {'scalar'});
options.RunBaseline = logical(options.RunBaseline);
options.SavePath = string(options.SavePath);
end

function row = emptyRow()
row = struct( ...
    "CaseNumber", NaN, ...
    "Example", "", ...
    "Status", "NOT_RUN", ...
    "Message", "", ...
    "BaselineSuccess", false, ...
    "BaselineSearch_s", NaN, ...
    "BaselineLength_deg", NaN, ...
    "MeshBuild_s", NaN, ...
    "MeshLeaves", NaN, ...
    "MeshRefinementCount", NaN, ...
    "MeshCompression", NaN, ...
    "MeshUnresolvedSamples", NaN, ...
    "OccupancyAccuracy", NaN, ...
    "FalseNegativeRate", NaN, ...
    "FalsePositiveRate", NaN, ...
    "SearchSuccess", false, ...
    "Search_s", NaN, ...
    "ExpandedNodes", NaN, ...
    "GeneratedNodes", NaN, ...
    "ExactValid", false, ...
    "ExactCollisionCount", NaN, ...
    "GoalError_deg", NaN, ...
    "PathLength_deg", NaN, ...
    "PathLengthRatio", NaN, ...
    "ArrivalTime_s", NaN);
end

function value = fieldOr(input, name, fallback)
if isfield(input, name) && ~isempty(input.(name))
    value = input.(name);
else
    value = fallback;
end
end

function output = applyDefaults(input, defaults)
output = input;
names = fieldnames(defaults);
for k = 1:numel(names)
    if ~isfield(output, names{k}) || isempty(output.(names{k}))
        output.(names{k}) = defaults.(names{k});
    end
end
end

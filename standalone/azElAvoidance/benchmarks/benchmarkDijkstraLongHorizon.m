function benchmark = benchmarkDijkstraLongHorizon(sampleCount)
%% Section 0: Header & Readme
% SYNTAX
%   benchmark = benchmarkDijkstraLongHorizon()
%   benchmark = benchmarkDijkstraLongHorizon(sampleCount)
%**************************************************************************
% PURPOSE
%   - Exercise event-compressed safe intervals over a day-scale obstacle.
%   - Verify the globally shortest eight-degree route is recovered by waiting.
%**************************************************************************
% INPUTS
%   - sampleCount (positive integer, optional)
%       Obstacle samples over 86,400 seconds; defaults to 86,401.
%**************************************************************************
% OUTPUTS
%   - benchmark (scalar struct)
%       Compression, storage, search, output, and plan measurements.
%**************************************************************************
% UNITS
%   - Angular quantities are degrees; temporal quantities are seconds.

%% Section 1: Build The Day-Scale Moving Gate
if nargin < 1
    sampleCount = 86401;
end
validateattributes(sampleCount, {'numeric'}, ...
    {'scalar', 'integer', '>=', 3});
time_s = linspace(0, 86400, sampleCount).';
azimuth_deg = cell(sampleCount, 1);
elevation_deg = repmat({[-2; -2; 2; 2; -2]}, sampleCount, 1);
for sampleIndex = 1:sampleCount
    gateCenterAzimuth_deg = 8 * (time_s(sampleIndex) > 43200);
    azimuth_deg{sampleIndex} = gateCenterAzimuth_deg + ...
        [-1; 1; 1; -1; -1];
end
azElData = makeAzElObstacleData( ...
    "Half-day gate", time_s, azimuth_deg, elevation_deg);

%% Section 2: Define The Planning Request
startState = struct( ...
    "time_s", 0, ...
    "position_deg", [-4 0], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
stopState = struct( ...
    "time_s", 86400, ...
    "position_deg", [4 0], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
limits = struct( ...
    "azimuth_deg", [-10 10], ...
    "elevation_deg", [-1.5 1.5], ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [1 1]);
options = struct( ...
    "SampleTime_s", 1, ...
    "ValidationStep_s", 1, ...
    "CollisionCheckStep_s", 0.25, ...
    "MaximumSafeIntervalSamples", 2048, ...
    "MaximumDepartureTrials", 64, ...
    "SafetyMargin_deg", 0.1, ...
    "MaxSearchTime_s", 30);

%% Section 3: Plan & Verify The Global-Optimum Certificate
benchmarkTimer = tic;
plan = planAzElDijkstra( ...
    azElData, startState, stopState, limits, options);
wallTime_s = toc(benchmarkTimer);
if ~plan.success
    error("benchmarkDijkstraLongHorizon:NoPath", ...
        "Planner failed: %s", plan.message);
end
if ~plan.optimalGlobally
    error("benchmarkDijkstraLongHorizon:NoCertificate", ...
        "Expected the direct angular optimum certificate.");
end

%% Section 4: Assemble & Print Benchmark Measurements
benchmark = struct( ...
    "inputSampleCount", sampleCount, ...
    "safeIntervalEventCount", ...
    plan.safeIntervalSearch.EventTimeCount, ...
    "eventCompressionRatio", sampleCount / ...
    plan.safeIntervalSearch.EventTimeCount, ...
    "outputSampleCount", numel(plan.time_s), ...
    "angularPathLength_deg", plan.angularPathLength_deg, ...
    "expandedNodeCount", plan.expandedNodeCount, ...
    "obstacleFieldStorageBytes", ...
    plan.obstacleField.EstimatedStorageBytes, ...
    "workspaceStorageBytes", ... % deprecated compatibility alias
    plan.obstacleField.EstimatedStorageBytes, ...
    "wallTime_s", wallTime_s, ...
    "plan", plan);
fprintf(['Long-horizon Dijkstra: %d input slices -> %d events ' ...
    '(%.1fx compression), %.3f s, %d expansions.\n'], ...
    benchmark.inputSampleCount, ...
    benchmark.safeIntervalEventCount, ...
    benchmark.eventCompressionRatio, wallTime_s, ...
    benchmark.expandedNodeCount);
end

function benchmark = benchmarkDijkstraLongHorizon(sampleCount)
%BENCHMARKADAPTIVEASTARLONGHORIZON Exercise a day-scale moving volume.
%
% benchmark = benchmarkDijkstraLongHorizon()
% benchmark = benchmarkDijkstraLongHorizon(sampleCount)
%
% The default uses 86,401 one-second obstacle slices. A gate blocks the
% direct chord for half the day, then moves away. The planner should return
% the globally shortest 8-degree path by waiting, without constructing a
% time-expanded search state for every second.

if nargin < 1
    sampleCount = 86401;
end
validateattributes(sampleCount, {'numeric'}, ...
    {'scalar', 'integer', '>=', 3});
time_s = linspace(0, 86400, sampleCount).';
azimuth = cell(sampleCount, 1);
elevation = repmat({[-2; -2; 2; 2; -2]}, sampleCount, 1);
for k = 1:sampleCount
    center = 8 * (time_s(k) > 43200);
    azimuth{k} = center + [-1; 1; 1; -1; -1];
end
data = makeAzElObstacleData( ...
    "Half-day gate", time_s, azimuth, elevation);
startState = boundaryState(0, [-4 0]);
stopState = boundaryState(86400, [4 0]);
limits = struct( ...
    "azimuth_deg", [-10 10], ...
    "elevation_deg", [-1.5 1.5], ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [1 1]);
options = struct( ...
    "SampleTime_s", 1, ...
    "ValidationStep_s", 1, ...
    "CollisionCheckStep_s", 0.25, ...
    "MaximumSafeIntervalSamples", 2048, ...
    "MaximumDepartureTrials", 64, ...
    "SafetyMargin_deg", 0.1, ...
    "MaxSearchTime_s", 30);

timer = tic;
plan = planAzElDijkstra( ...
    data, startState, stopState, limits, options);
wallTime = toc(timer);
if ~plan.success
    error("benchmarkDijkstraLongHorizon:NoPath", ...
        "Planner failed: %s", plan.message);
end
if ~plan.optimalGlobally
    error("benchmarkDijkstraLongHorizon:NoCertificate", ...
        "Expected the direct angular optimum certificate.");
end

benchmark = struct( ...
    "inputSampleCount", sampleCount, ...
    "safeIntervalEventCount", ...
    plan.safeIntervalSearch.EventTimeCount, ...
    "eventCompressionRatio", sampleCount / ...
    plan.safeIntervalSearch.EventTimeCount, ...
    "outputSampleCount", numel(plan.time_s), ...
    "angularPathLength_deg", plan.angularPathLength_deg, ...
    "expandedNodeCount", plan.expandedNodeCount, ...
    "workspaceStorageBytes", ...
    plan.workspace.EstimatedStorageBytes, ...
    "wallTime_s", wallTime, ...
    "plan", plan);
fprintf(['Long-horizon Dijkstra: %d input slices -> %d events ' ...
    '(%.1fx compression), %.3f s, %d expansions.\n'], ...
    benchmark.inputSampleCount, ...
    benchmark.safeIntervalEventCount, ...
    benchmark.eventCompressionRatio, wallTime, ...
    benchmark.expandedNodeCount);
end

function state = boundaryState(time_s, position)
state = struct( ...
    "time_s", time_s, ...
    "position_deg", position, ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
end

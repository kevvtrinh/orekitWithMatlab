function report = benchmarkRandomizedPlannerAgent( ...
        scenarioCount, rootSeed, options)
%BENCHMARKRANDOMIZEDPLANNERAGENT Run a no-rejection held-out campaign.
%
% report = benchmarkRandomizedPlannerAgent()
% report = benchmarkRandomizedPlannerAgent(scenarioCount, rootSeed, options)
%
% Five scenario families receive independent reproducible seeds. A case is
% never regenerated because either planner fails. Conditional success is
% measured where the robust reference planner proves a route exists, while
% reference failures remain in the exported result table.

if nargin < 1 || isempty(scenarioCount)
    scenarioCount = 100;
end
if nargin < 2 || isempty(rootSeed)
    rootSeed = 20260730;
end
if nargin < 3
    options = struct();
end
defaults = struct( ...
    "AgentArtifact", [], ...
    "Verbose", true, ...
    "OutputFolder", "", ...
    "MinimumOverallSuccessRate", 0.95, ...
    "MinimumConditionalSuccessRate", 0.95, ...
    "MaximumPathRatio95", 1.10, ...
    "AssertAcceptance", false);
defaultNames = fieldnames(defaults);
for defaultIndex = 1:numel(defaultNames)
    defaultName = defaultNames{defaultIndex};
    if ~isfield(options, defaultName) || isempty(options.(defaultName))
        options.(defaultName) = defaults.(defaultName);
    end
end
validateattributes(scenarioCount, {'numeric'}, ...
    {'scalar', 'integer', '>=', 5});
validateattributes(rootSeed, {'numeric'}, ...
    {'scalar', 'integer', 'positive', '<=', intmax("int32")});
validateattributes(options.MinimumConditionalSuccessRate, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<=', 1});
validateattributes(options.MinimumOverallSuccessRate, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<=', 1});
validateattributes(options.MaximumPathRatio95, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 1});
validateattributes(options.Verbose, ...
    {'logical', 'numeric'}, {'scalar'});
validateattributes(options.AssertAcceptance, ...
    {'logical', 'numeric'}, {'scalar'});
options.Verbose = logical(options.Verbose);
options.AssertAcceptance = logical(options.AssertAcceptance);

families = [ ...
    "wall", "slalom", "trap", "movingGates", "rotatingRods"];
familyCount = numel(families);
campaignStream = RandStream( ...
    "mt19937ar", "Seed", double(rootSeed));
scenarioSeeds = randi(campaignStream, ...
    intmax("int32"), scenarioCount, 1);
familyIndex = mod((0:scenarioCount - 1).', familyCount) + 1;
familyIndex = familyIndex(randperm(campaignStream, scenarioCount));
scenarioFamily = families(familyIndex).';

generationSuccess = false(scenarioCount, 1);
packingElapsed_s = nan(scenarioCount, 1);
referenceSuccess = false(scenarioCount, 1);
agentSuccess = false(scenarioCount, 1);
agentUnsafeAcceptance = false(scenarioCount, 1);
referenceElapsed_s = nan(scenarioCount, 1);
agentElapsed_s = nan(scenarioCount, 1);
referencePath_deg = nan(scenarioCount, 1);
agentPath_deg = nan(scenarioCount, 1);
pathRatio = nan(scenarioCount, 1);
referenceCompletion_s = nan(scenarioCount, 1);
agentCompletion_s = nan(scenarioCount, 1);
completionDelay_s = nan(scenarioCount, 1);
predictedProfile = strings(scenarioCount, 1);
selectedProfile = strings(scenarioCount, 1);
problemMode = strings(scenarioCount, 1);
selectionSource = strings(scenarioCount, 1);
agentAbstained = false(scenarioCount, 1);
agentAttemptCount = zeros(scenarioCount, 1);
referenceMessage = strings(scenarioCount, 1);
agentMessage = strings(scenarioCount, 1);
generationMessage = strings(scenarioCount, 1);

campaignTimer = tic;
for scenarioIndex = 1:scenarioCount
    if options.Verbose
        fprintf("Random validation %3d/%3d: %-12s seed %d\n", ...
            scenarioIndex, scenarioCount, ...
            scenarioFamily(scenarioIndex), ...
            scenarioSeeds(scenarioIndex));
    end
    try
        problem = makeRandomAzElPlannerScenario( ...
            scenarioSeeds(scenarioIndex), ...
            scenarioFamily(scenarioIndex));
        packingTimer = tic;
        workspace = buildAzElTimeObstacleWorkspace(problem.azElData);
        packingElapsed_s(scenarioIndex) = toc(packingTimer);
        generationSuccess(scenarioIndex) = true;
    catch generationError
        generationMessage(scenarioIndex) = string(generationError.identifier) + ": " + ...
            string(generationError.message);
        continue;
    end

    try
        referenceTimer = tic;
        referencePlan = planAzElDijkstra( ...
            workspace, problem.initialState, problem.goalState, ...
            problem.limits, problem.referenceOptions);
        referenceElapsed_s(scenarioIndex) = toc(referenceTimer);
        referenceSuccess(scenarioIndex) = referencePlan.success && ...
            referencePlan.exactCollisionValidated;
        referenceMessage(scenarioIndex) = referencePlan.message;
        if referenceSuccess(scenarioIndex)
            referencePath_deg(scenarioIndex) = referencePlan.angularPathLength_deg;
            referenceMoving = any( ...
                abs(referencePlan.velocity_deg_s) > 1e-9, 2);
            finalReferenceMotion = find( ...
                referenceMoving, 1, "last");
            if isempty(finalReferenceMotion)
                referenceCompletion_s(scenarioIndex) = referencePlan.startState.time_s;
            else
                referenceCompletion_s(scenarioIndex) = referencePlan.time_s(finalReferenceMotion);
            end
        end
    catch referenceError
        referenceMessage(scenarioIndex) = string(referenceError.identifier) + ": " + ...
            string(referenceError.message);
    end

    try
        agentOptions = problem.agentOptions;
        if ~isempty(options.AgentArtifact)
            agentOptions.AgentArtifact = options.AgentArtifact;
        end
        agentTimer = tic;
        agentPlan = planAzElWithAgent( ...
            workspace, problem.initialState, problem.goalState, ...
            problem.limits, agentOptions);
        agentElapsed_s(scenarioIndex) = toc(agentTimer);
        agentSuccess(scenarioIndex) = agentPlan.success && ...
            agentPlan.exactCollisionValidated;
        agentUnsafeAcceptance(scenarioIndex) = agentPlan.success && ...
            ~agentPlan.exactCollisionValidated;
        agentMessage(scenarioIndex) = agentPlan.message;
        predictedProfile(scenarioIndex) = agentPlan.agent.PredictedProfileName;
        selectedProfile(scenarioIndex) = agentPlan.agent.SelectedProfileName;
        problemMode(scenarioIndex) = agentPlan.agent.ProblemMode;
        selectionSource(scenarioIndex) = agentPlan.agent.SelectionSource;
        agentAbstained(scenarioIndex) = agentPlan.agent.AbstainedFromLearnedConfidence;
        agentAttemptCount(scenarioIndex) = numel(agentPlan.agent.Attempts);
        if agentSuccess(scenarioIndex)
            agentPath_deg(scenarioIndex) = agentPlan.angularPathLength_deg;
            agentMoving = any( ...
                abs(agentPlan.velocity_deg_s) > 1e-9, 2);
            finalAgentMotion = find(agentMoving, 1, "last");
            if isempty(finalAgentMotion)
                agentCompletion_s(scenarioIndex) = agentPlan.startState.time_s;
            else
                agentCompletion_s(scenarioIndex) = agentPlan.time_s(finalAgentMotion);
            end
        end
    catch agentError
        agentMessage(scenarioIndex) = string(agentError.identifier) + ": " + ...
            string(agentError.message);
    end

    mutualSuccess = referenceSuccess(scenarioIndex) && ...
        agentSuccess(scenarioIndex);
    if mutualSuccess
        pathRatio(scenarioIndex) = agentPath_deg(scenarioIndex) / ...
            referencePath_deg(scenarioIndex);
        completionDelay_s(scenarioIndex) = agentCompletion_s(scenarioIndex) - ...
            referenceCompletion_s(scenarioIndex);
    end
end

results = table( ...
    (1:scenarioCount).', scenarioSeeds, scenarioFamily, ...
    generationSuccess, packingElapsed_s, ...
    referenceSuccess, agentSuccess, agentUnsafeAcceptance, ...
    referenceElapsed_s, agentElapsed_s, ...
    referencePath_deg, agentPath_deg, pathRatio, ...
    referenceCompletion_s, agentCompletion_s, completionDelay_s, ...
    predictedProfile, selectedProfile, problemMode, selectionSource, ...
    agentAbstained, agentAttemptCount, ...
    generationMessage, referenceMessage, agentMessage, ...
    'VariableNames', cellstr([ ...
        "Scenario", "Seed", "Family", ...
        "GenerationSuccess", "PackingElapsed_s", ...
        "ReferenceSuccess", "AgentSuccess", ...
        "AgentUnsafeAcceptance", ...
        "ReferenceElapsed_s", "AgentElapsed_s", ...
        "ReferencePath_deg", "AgentPath_deg", "PathRatio", ...
        "ReferenceCompletion_s", "AgentCompletion_s", ...
        "CompletionDelay_s", "PredictedProfile", ...
        "SelectedProfile", "ProblemMode", "SelectionSource", ...
        "AgentAbstained", "AgentAttemptCount", ...
        "GenerationMessage", "ReferenceMessage", "AgentMessage"]));

familyScenarioCount = zeros(familyCount, 1);
familyReferenceSuccessCount = zeros(familyCount, 1);
familyAgentSuccessCount = zeros(familyCount, 1);
familyConditionalSuccessRate = nan(familyCount, 1);
familyMedianRuntimeRatio = nan(familyCount, 1);
familyMedianPathRatio = nan(familyCount, 1);
familyPathRatio95 = nan(familyCount, 1);
for currentFamilyIndex = 1:familyCount
    inFamily = scenarioFamily == families(currentFamilyIndex);
    familyScenarioCount(currentFamilyIndex) = nnz(inFamily);
    familyReferenceSuccessCount(currentFamilyIndex) = nnz(referenceSuccess & inFamily);
    familyAgentSuccessCount(currentFamilyIndex) = nnz(agentSuccess & inFamily);
    referenceSolvedInFamily = referenceSuccess & inFamily;
    if any(referenceSolvedInFamily)
        familyConditionalSuccessRate(currentFamilyIndex) = nnz( ...
            agentSuccess & referenceSolvedInFamily) / ...
            nnz(referenceSolvedInFamily);
    end
    mutualInFamily = referenceSuccess & agentSuccess & inFamily;
    if any(mutualInFamily)
        familyRuntimeRatio = agentElapsed_s(mutualInFamily) ./ ...
            referenceElapsed_s(mutualInFamily);
        familyPathRatio = pathRatio(mutualInFamily);
        familyMedianRuntimeRatio(currentFamilyIndex) = median(familyRuntimeRatio);
        familyMedianPathRatio(currentFamilyIndex) = median(familyPathRatio);
        sortedFamilyPathRatio = sort(familyPathRatio);
        familyRatio95Index = max( ...
            1, ceil(0.95 * numel(sortedFamilyPathRatio)));
        familyPathRatio95(currentFamilyIndex) = sortedFamilyPathRatio( ...
            familyRatio95Index);
    end
end
familySummary = table( ...
    families.', familyScenarioCount, ...
    familyReferenceSuccessCount, familyAgentSuccessCount, ...
    familyConditionalSuccessRate, familyMedianRuntimeRatio, ...
    familyMedianPathRatio, familyPathRatio95, ...
    'VariableNames', cellstr([ ...
        "Family", "ScenarioCount", "ReferenceSuccessCount", ...
        "AgentSuccessCount", "ConditionalSuccessRate", ...
        "MedianRuntimeRatio", "MedianPathRatio", "PathRatio95"]));

referenceSolved = referenceSuccess;
mutualSuccess = referenceSuccess & agentSuccess;
referenceSuccessCount = nnz(referenceSolved);
agentSuccessOnReferenceCount = nnz(mutualSuccess);
if referenceSuccessCount > 0
    conditionalSuccessRate = agentSuccessOnReferenceCount / referenceSuccessCount;
else
    conditionalSuccessRate = 0;
end
if any(mutualSuccess)
    runtimeRatio = agentElapsed_s(mutualSuccess) ./ ...
        referenceElapsed_s(mutualSuccess);
    successfulPathRatio = pathRatio(mutualSuccess);
    sortedPathRatio = sort(successfulPathRatio);
    pathRatio95Index = max( ...
        1, ceil(0.95 * numel(sortedPathRatio)));
    pathRatio95 = sortedPathRatio(pathRatio95Index);
    medianPathRatio = median(successfulPathRatio);
    medianRuntimeRatio = median(runtimeRatio);
else
    pathRatio95 = Inf;
    medianPathRatio = Inf;
    medianRuntimeRatio = Inf;
end
unsafeAcceptanceCount = nnz(agentUnsafeAcceptance);
generatedScenarioCount = nnz(generationSuccess);
overallSuccessRate = nnz(agentSuccess) / ...
    max(generatedScenarioCount, 1);
minimumOverallSuccessRate = options.MinimumOverallSuccessRate;
overallSuccessRatePassed = overallSuccessRate >= minimumOverallSuccessRate;
minimumSuccessRate = options.MinimumConditionalSuccessRate;
successRatePassed = conditionalSuccessRate >= minimumSuccessRate;
acceptancePassed = all(generationSuccess) && ...
    unsafeAcceptanceCount == 0 && ...
    overallSuccessRatePassed && ...
    successRatePassed && ...
    pathRatio95 <= options.MaximumPathRatio95;
report = struct( ...
    "Format", "RandomizedAzElPlannerAgentValidation", ...
    "Version", 1, ...
    "CreatedUtc", string(datetime("now", "TimeZone", "UTC")), ...
    "RootSeed", double(rootSeed), ...
    "ScenarioCount", scenarioCount, ...
    "Results", results, ...
    "FamilySummary", familySummary, ...
    "GenerationFailureCount", nnz(~generationSuccess), ...
    "ReferenceSuccessCount", referenceSuccessCount, ...
    "AgentSuccessCount", nnz(agentSuccess), ...
    "OverallSuccessRate", overallSuccessRate, ...
    "AgentSuccessOnReferenceCount", agentSuccessOnReferenceCount, ...
    "ConditionalSuccessRate", conditionalSuccessRate, ...
    "UnsafeAcceptanceCount", unsafeAcceptanceCount, ...
    "MedianRuntimeRatio", medianRuntimeRatio, ...
    "MedianPathRatio", medianPathRatio, ...
    "PathRatio95", pathRatio95, ...
    "AcceptancePassed", acceptancePassed, ...
    "AcceptanceThresholds", struct( ...
        "MinimumOverallSuccessRate", ...
            options.MinimumOverallSuccessRate, ...
        "MinimumConditionalSuccessRate", ...
            options.MinimumConditionalSuccessRate, ...
        "MaximumPathRatio95", options.MaximumPathRatio95), ...
    "CampaignElapsed_s", toc(campaignTimer));

disp(familySummary);
fprintf("Random validation: %d/%d overall and %d/%d reference-solvable " + ...
    "cases passed (%.1f%% conditional), p95 path ratio %.3f, " + ...
    "median runtime ratio %.3f, " + ...
    "unsafe accepts %d.\n", ...
    nnz(agentSuccess), generatedScenarioCount, ...
    agentSuccessOnReferenceCount, referenceSuccessCount, ...
    100 * conditionalSuccessRate, pathRatio95, ...
    medianRuntimeRatio, unsafeAcceptanceCount);
if strlength(string(options.OutputFolder)) > 0
    outputFolder = char(options.OutputFolder);
    if ~isfolder(outputFolder)
        mkdir(outputFolder);
    end
    writetable(results, fullfile( ...
        outputFolder, "randomizedAgentValidation.csv"));
    writetable(familySummary, fullfile( ...
        outputFolder, "randomizedAgentValidationSummary.csv"));
    save(fullfile(outputFolder, ...
        "randomizedAgentValidation.mat"), "report", "-v7.3");
end
if options.AssertAcceptance && ~acceptancePassed
    error("benchmarkRandomizedPlannerAgent:AcceptanceFailed", ...
        "Randomized campaign did not meet its declared thresholds.");
end
end

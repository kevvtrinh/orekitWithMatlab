function testDirectWaitAndSlewIsGloballyShortest(testCase)
time_s = (0:20).';
azimuth = cell(numel(time_s), 1);
elevation = cell(numel(time_s), 1);
for k = 1:numel(time_s)
    center = 8 * (time_s(k) > 7);
    azimuth{k} = center + [-1; 1; 1; -1; -1];
    elevation{k} = [-2; -2; 2; 2; -2];
end
data = makeAzElObstacleData( ...
    "Opening gate", time_s, azimuth, elevation);
[startState, stopState, limits] = standardProblem(20);
options = struct( ...
    "SampleTime_s", 0.25, ...
    "SafetyMargin_deg", 0.1);

plan = planAzElSpaceTimeFunnel( ...
    data, startState, stopState, limits, options);

verifyTrue(testCase, plan.success);
verifyEqual(testCase, plan.method, "directSafeIntervalCertificate");
verifyTrue(testCase, plan.optimalGlobally);
verifyEqual(testCase, plan.angularPathLength_deg, 8, ...
    "AbsTol", 1e-9);
verifyEqual(testCase, plan.suboptimalityBound, 1, ...
    "AbsTol", 1e-12);
verifyTrue(testCase, any(plan.isWaiting));
verifyPlan(testCase, plan, options);
end

function testMovingVolumeForcesSafeIntervalDetour(testCase)
time_s = (0:20).';
azimuth = cell(numel(time_s), 1);
elevation = cell(numel(time_s), 1);
for k = 1:numel(time_s)
    center = 0.35 * sin(time_s(k) / 3);
    azimuth{k} = [-1; 1; 1; -1; -1];
    elevation{k} = center + [-2; -2; 2; 2; -2];
end
data = makeAzElObstacleData( ...
    "Moving wall", time_s, azimuth, elevation);
[startState, stopState, limits] = standardProblem(20);
options = struct( ...
    "SampleTime_s", 0.25, ...
    "GuideGridStep_deg", 1, ...
    "SafetyMargin_deg", 0.1, ...
    "EnableARARefinement", false, ...
    "FallbackToGlobalSearch", false, ...
    "MaxSearchTime_s", 8);

plan = planAzElSpaceTimeFunnel( ...
    data, startState, stopState, limits, options);

verifyTrue(testCase, plan.success);
verifyEqual(testCase, plan.method, ...
    "eventCompressedSafeIntervalFunnel");
verifyGreaterThan(testCase, plan.angularPathLength_deg, 8);

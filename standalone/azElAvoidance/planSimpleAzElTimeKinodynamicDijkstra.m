function canReachDestination = ...
        buildSimpleDijkstraAxisBackwardReachability( ...
        positionGrid_deg, velocityGrid_deg_s, ...
        accelerationGrid_deg_s2, jerkValues_deg_s3, timeStep_s, ...
        timeStepCount, ...
        destinationPosition_deg, destinationVelocity_deg_s, ...
        destinationAcceleration_deg_s2, positionTolerance_deg, ...
        velocityTolerance_deg_s, accelerationTolerance_deg_s2, ...
        positionLimits_deg, maximumVelocity_deg_s, ...
        maximumAcceleration_deg_s2, allowPositionWrap)
%% Section 0: Header & Readme
% SYNTAX
%   canReachDestination = ...
%       buildSimpleDijkstraAxisBackwardReachability(...)
%**************************************************************************
% PURPOSE
%   - Mark every one-axis lattice state that can reach the complete terminal
%     lattice under at least one remaining discrete jerk sequence.
%   - Ignore obstacles and interior extrema so the table is a conservative
%     pruning test: false proves dynamic unreachability, while true makes no
%     collision-feasibility claim.
%**************************************************************************
% INPUTS
%   - positionGrid_deg, velocityGrid_deg_s,
%     accelerationGrid_deg_s2 (numeric rows)
%       One-axis state lattices.
%   - jerkValues_deg_s3 (numeric vector)
%       Available one-axis jerk values.
%   - timeStep_s (positive numeric scalar)
%       Uniform transition duration.
%   - timeStepCount (nonnegative integer scalar)
%       Number of transitions in the complete search horizon.
%   - destinationPosition_deg, destinationVelocity_deg_s,
%     destinationAcceleration_deg_s2 (numeric scalars)
%       Exact requested terminal components.
%   - positionTolerance_deg, velocityTolerance_deg_s,
%     accelerationTolerance_deg_s2 (nonnegative numeric scalars)
%       Terminal component tolerances.
%   - positionLimits_deg (1-by-2 numeric row)
%       One-axis position limits.
%   - maximumVelocity_deg_s, maximumAcceleration_deg_s2
%       Symmetric dynamic limits.
%   - allowPositionWrap (logical scalar)
%       Whether position uses the complete wrapped azimuth domain.
%**************************************************************************
% OUTPUTS
%   - canReachDestination (logical 4-D array)
%       Position-by-velocity-by-acceleration-by-time reachability.
%**************************************************************************
% UNITS
%   - Field and argument suffixes state their physical units.
positionCount = numel(positionGrid_deg);
velocityCount = numel(velocityGrid_deg_s);
accelerationCount = numel(accelerationGrid_deg_s2);
timeCount = timeStepCount + 1;
canReachDestination = false( ...
    positionCount, velocityCount, accelerationCount, timeCount);

positionError_deg = destinationPosition_deg - positionGrid_deg;
if allowPositionWrap
    positionError_deg = mod(positionError_deg + 180, 360) - 180;
end
terminalPosition = abs(positionError_deg) <= positionTolerance_deg;
terminalVelocity = abs(destinationVelocity_deg_s - ...
    velocityGrid_deg_s) <= velocityTolerance_deg_s;
terminalAcceleration = abs(destinationAcceleration_deg_s2 - ...
    accelerationGrid_deg_s2) <= accelerationTolerance_deg_s2;
canReachDestination(:, :, :, end) = reshape(terminalPosition, [], 1, 1) & ...
    reshape(terminalVelocity, 1, [], 1) & ...
    reshape(terminalAcceleration, 1, 1, []);

limitTolerance = 1e-12;
for timeIndex = timeStepCount:-1:1
    for positionIndex = 1:positionCount
        currentPosition_deg = positionGrid_deg(positionIndex);
        for velocityIndex = 1:velocityCount
            currentVelocity_deg_s = velocityGrid_deg_s(velocityIndex);
            for accelerationIndex = 1:accelerationCount
                currentAcceleration_deg_s2 = ...
                    accelerationGrid_deg_s2(accelerationIndex);
                for jerkIndex = 1:numel(jerkValues_deg_s3)
                    appliedJerk_deg_s3 = jerkValues_deg_s3(jerkIndex);
                    nextAcceleration_deg_s2 = ...
                        currentAcceleration_deg_s2 + ...
                        appliedJerk_deg_s3 * timeStep_s;
                    nextVelocity_deg_s = currentVelocity_deg_s + ...
                        currentAcceleration_deg_s2 * timeStep_s + ...
                        0.5 * appliedJerk_deg_s3 * timeStep_s^2;
                    propagatedPosition_deg = currentPosition_deg + ...
                        currentVelocity_deg_s * timeStep_s + ...
                        0.5 * currentAcceleration_deg_s2 * timeStep_s^2 + ...
                        (1 / 6) * appliedJerk_deg_s3 * timeStep_s^3;

                    if abs(nextAcceleration_deg_s2) > ...
                            maximumAcceleration_deg_s2 + limitTolerance || ...
                            abs(nextVelocity_deg_s) > ...
                            maximumVelocity_deg_s + limitTolerance
                        continue;
                    end
                    if allowPositionWrap
                        propagatedPosition_deg = mod( ...
                            propagatedPosition_deg - positionLimits_deg(1), ...
                            360) + positionLimits_deg(1);
                        positionDifference_deg = mod(positionGrid_deg - ...
                            propagatedPosition_deg + 180, 360) - 180;
                    else
                        if propagatedPosition_deg < ...
                                positionLimits_deg(1) - limitTolerance || ...
                                propagatedPosition_deg > ...
                                positionLimits_deg(2) + limitTolerance
                            continue;
                        end
                        positionDifference_deg = positionGrid_deg - ...
                            propagatedPosition_deg;
                    end

                    [~, nextPositionIndex] = ...
                        min(abs(positionDifference_deg));
                    [~, nextVelocityIndex] = min(abs( ...
                        velocityGrid_deg_s - nextVelocity_deg_s));
                    [~, nextAccelerationIndex] = min(abs( ...
                        accelerationGrid_deg_s2 - ...
                        nextAcceleration_deg_s2));
                    if canReachDestination( ...
                            nextPositionIndex, nextVelocityIndex, ...
                            nextAccelerationIndex, timeIndex + 1)
                        canReachDestination( ...
                            positionIndex, velocityIndex, ...
                            accelerationIndex, timeIndex) = true;
                        break;
                    end
                end
            end
        end
    end
end
end


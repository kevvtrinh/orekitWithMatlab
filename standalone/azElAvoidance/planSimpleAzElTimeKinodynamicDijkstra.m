function options = resolveSimpleDijkstraOptions( ...
        options, defaultOptions, limits)
%% Section 0: Header & Readme
% SYNTAX
%   options = resolveSimpleDijkstraOptions(options, defaults, limits)
%**************************************************************************
% PURPOSE
%   - Apply defaults and validate lattice compatibility before allocation.
%**************************************************************************
% INPUTS
%   - options (scalar struct)
%       Requested partial planner options.
%   - defaultOptions (scalar struct)
%       Fully populated argument-independent defaults.
%   - limits (scalar struct)
%       Normalized physical limits.
%**************************************************************************
% OUTPUTS
%   - options (scalar struct)
%       Resolved and validated options.
%**************************************************************************
% UNITS
%   - Field suffixes state their physical units.
if ~isstruct(options) || ~isscalar(options)
    error("planSimpleAzElTimeKinodynamicDijkstra:InvalidOptions", ...
        "options must be a scalar struct.");
end
unknownFields = setdiff(fieldnames(options), fieldnames(defaultOptions), ...
    "stable");
if ~isempty(unknownFields)
    warning("planSimpleAzElTimeKinodynamicDijkstra:UnknownOptions", ...
        "Ignoring unknown option fields: %s.", ...
        strjoin(string(unknownFields), ", "));
    options = rmfield(options, unknownFields);
end
resolvedOptions = defaultOptions;
providedFields = fieldnames(options);
for fieldIndex = 1:numel(providedFields)
    fieldName = providedFields{fieldIndex};
    if ~isempty(options.(fieldName)) || fieldName == "jerkCommands_deg_s3"
        resolvedOptions.(fieldName) = options.(fieldName);
    end
end
options = resolvedOptions;

% Grid ratios within this relative-scale tolerance represent the same
% integer cell count despite floating-point division noise.
gridCompatibilityTolerance = 1e-9;
limitTolerance = 1e-12;

validateattributes(options.timeStep_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(options.timeStepSchedule_s, {'numeric'}, ...
    {'vector', 'real', 'finite', 'positive'});
options.timeStepSchedule_s = unique( ...
    double(options.timeStepSchedule_s(:).'), "stable");
options.timeStepSchedule_s = sort( ...
    options.timeStepSchedule_s, "descend");
stepFields = ["positionStep_deg", "velocityStep_deg_s", ...
    "accelerationStep_deg_s2"];
for fieldName = stepFields
    validateattributes(options.(fieldName), {'numeric'}, ...
        {'vector', 'numel', 2, 'real', 'finite', 'positive'});
    options.(fieldName) = reshape(double(options.(fieldName)), 1, 2);
end
validateattributes(options.positionStepSchedule_deg, {'numeric'}, ...
    {'vector', 'real', 'finite', 'positive'});
options.positionStepSchedule_deg = unique( ...
    double(options.positionStepSchedule_deg(:).'), "stable");

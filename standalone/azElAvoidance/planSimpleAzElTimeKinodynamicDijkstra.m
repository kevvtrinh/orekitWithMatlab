function isBlocked = simpleDijkstraTransitionHasCollision( ...
        obstacleField, currentPosition_deg, currentVelocity_deg_s, ...
        currentAcceleration_deg_s2, appliedJerk_deg_s3, currentTime_s, ...
        timeStep_s, collisionCheckStep_s, limits, options)
%% Section 0: Header & Readme
% SYNTAX
%   isBlocked = simpleDijkstraTransitionHasCollision(...)
%**************************************************************************
% PURPOSE
%   - Sample one complete constant-jerk transition for polygon collision
%     and elevation-bound violations between lattice endpoints.
%**************************************************************************
% INPUTS
%   - obstacleField (scalar struct)
%       Packed moving polygons used by the occupancy raster.
%   - currentPosition_deg (1-by-2 numeric row)
%       Current azimuth and elevation.
%   - currentVelocity_deg_s (1-by-2 numeric row)
%       Current azimuth and elevation velocity.
%   - currentAcceleration_deg_s2 (1-by-2 numeric row)
%       Current azimuth and elevation acceleration.
%   - appliedJerk_deg_s3 (1-by-2 numeric row)
%       Constant jerk command for the transition.
%   - currentTime_s, timeStep_s, collisionCheckStep_s (numeric scalars)
%       Current time, transition duration, and maximum sample spacing.
%   - limits, options (scalar structs)
%       Physical limits and resolved planner options.
%**************************************************************************
% OUTPUTS
%   - isBlocked (logical scalar)
%       True when any sampled point is occupied or outside elevation bounds.
%**************************************************************************
% UNITS
%   - Field and argument suffixes state their physical units.
sampleCount = ceil(timeStep_s / collisionCheckStep_s);
% Sampled elevation checks share the endpoint-limit noise tolerance used by
% the visible search loop; this does not enlarge the discrete state domain.
limitTolerance = 1e-12;
sampleOffset_s = linspace( ...
    timeStep_s / sampleCount, timeStep_s, sampleCount).';
samplePosition_deg = currentPosition_deg + ...
    sampleOffset_s .* currentVelocity_deg_s + ...
    0.5 * sampleOffset_s.^2 .* currentAcceleration_deg_s2 + ...
    (1 / 6) * sampleOffset_s.^3 .* appliedJerk_deg_s3;
if options.allowAzimuthWrap
    samplePosition_deg(:, 1) = mod( ...
        samplePosition_deg(:, 1) - limits.azimuth_deg(1), 360) + ...
        limits.azimuth_deg(1);
end
sampleTime_s = currentTime_s + sampleOffset_s;
sampleOutsideElevation = ...
    samplePosition_deg(:, 2) < ...
    limits.elevation_deg(1) - limitTolerance | ...
    samplePosition_deg(:, 2) > ...
    limits.elevation_deg(2) + limitTolerance;
sampleOccupied = queryAzElTimeObstacle( ...
    obstacleField, samplePosition_deg(:, 1), samplePosition_deg(:, 2), ...
    sampleTime_s, options.collisionQueryOptions);
isBlocked = any(sampleOutsideElevation | sampleOccupied);
end

function [frontierStateIndex, frontierCost, ...
        frontierLocationByStateIndex, frontierCount] = ...
        pushOrDecreaseSimpleDijkstraFrontier( ...
        frontierStateIndex, frontierCost, ...
        frontierLocationByStateIndex, frontierCount, ...
        stateIndex, stateCost)
%% Section 0: Header & Readme
% SYNTAX
%   [indices, costs, locations, count] = ...
%       pushOrDecreaseSimpleDijkstraFrontier( ...
%       indices, costs, locations, count, stateIndex, stateCost)
%**************************************************************************
% PURPOSE
%   - Insert one unsettled state or decrease its cost in an indexed binary
%     min-heap without creating stale duplicate entries.
%   - Break equal-cost ties by generated-state index to reproduce the
%     original scan frontier's deterministic choice.
%**************************************************************************
% INPUTS
%   - frontierStateIndex (uint32 vector)
%       Generated-state index at each heap location.
%   - frontierCost (numeric vector)
%       Dijkstra cost at each heap location.
%   - frontierLocationByStateIndex (uint32 vector)
%       Reverse map from generated-state index to heap location.
%   - frontierCount (nonnegative integer scalar)
%       Number of active heap entries.
%   - stateIndex (positive integer scalar)
%       Generated-state row to insert or update.
%   - stateCost (nonnegative numeric scalar)
%       New best-known Dijkstra cost.
%**************************************************************************
% OUTPUTS
%   - frontierStateIndex, frontierCost,
%     frontierLocationByStateIndex, frontierCount
%       Updated indexed min-heap storage.
%**************************************************************************
% UNITS
%   - Costs use the planner transition-cost units; indices are dimensionless.
frontierLocation = double(frontierLocationByStateIndex(stateIndex));
if frontierLocation == 0
    frontierCount = frontierCount + 1;
    frontierLocation = frontierCount;
    frontierStateIndex(frontierLocation) = uint32(stateIndex);
    frontierLocationByStateIndex(stateIndex) = uint32(frontierLocation);
end
frontierCost(frontierLocation) = stateCost;

while frontierLocation > 1
    parentLocation = floor(frontierLocation / 2);
    parentCost = frontierCost(parentLocation);
    parentStateIndex = double(frontierStateIndex(parentLocation));
    currentCost = frontierCost(frontierLocation);
    currentStateIndex = double(frontierStateIndex(frontierLocation));
    parentPrecedesCurrent = parentCost < currentCost || ( ...
        parentCost == currentCost && parentStateIndex < currentStateIndex);
    if parentPrecedesCurrent
        break;
    end

    frontierStateIndex([parentLocation, frontierLocation]) = ...
        frontierStateIndex([frontierLocation, parentLocation]);
    frontierCost([parentLocation, frontierLocation]) = ...
        frontierCost([frontierLocation, parentLocation]);
    frontierLocationByStateIndex(currentStateIndex) = ...
        uint32(parentLocation);
    frontierLocationByStateIndex(parentStateIndex) = ...
        uint32(frontierLocation);
    frontierLocation = parentLocation;
end
end

function [stateIndex, frontierStateIndex, frontierCost, ...
        frontierLocationByStateIndex, frontierCount] = ...
        popSimpleDijkstraFrontier( ...
        frontierStateIndex, frontierCost, ...
        frontierLocationByStateIndex, frontierCount)
%% Section 0: Header & Readme
% SYNTAX
%   [stateIndex, indices, costs, locations, count] = ...
%       popSimpleDijkstraFrontier(indices, costs, locations, count)
%**************************************************************************
% PURPOSE
%   - Remove and return the stable minimum-cost state from the indexed
%     binary-heap Dijkstra frontier.
%**************************************************************************
% INPUTS
%   - frontierStateIndex (uint32 vector)
%       Generated-state index at each heap location.
%   - frontierCost (numeric vector)
%       Dijkstra cost at each heap location.
%   - frontierLocationByStateIndex (uint32 vector)
%       Reverse map from generated-state index to heap location.
%   - frontierCount (nonnegative integer scalar)
%       Number of active heap entries.
%**************************************************************************
% OUTPUTS
%   - stateIndex (nonnegative integer scalar)
%       Minimum entry, or zero when the frontier is empty.
%   - frontierStateIndex, frontierCost,
%     frontierLocationByStateIndex, frontierCount
%       Updated indexed min-heap storage.
%**************************************************************************
% UNITS
%   - Costs use the planner transition-cost units; indices are dimensionless.
if frontierCount == 0
    stateIndex = 0;
    return;
end

stateIndex = double(frontierStateIndex(1));
frontierLocationByStateIndex(stateIndex) = uint32(0);
if frontierCount == 1
    frontierStateIndex(1) = uint32(0);
    frontierCost(1) = Inf;
    frontierCount = 0;
    return;
end

lastStateIndex = double(frontierStateIndex(frontierCount));
frontierStateIndex(1) = uint32(lastStateIndex);
frontierCost(1) = frontierCost(frontierCount);
frontierLocationByStateIndex(lastStateIndex) = uint32(1);
frontierStateIndex(frontierCount) = uint32(0);
frontierCost(frontierCount) = Inf;
frontierCount = frontierCount - 1;

frontierLocation = 1;
while true
    leftChildLocation = 2 * frontierLocation;
    if leftChildLocation > frontierCount
        break;
    end
    rightChildLocation = leftChildLocation + 1;
    minimumChildLocation = leftChildLocation;
    if rightChildLocation <= frontierCount
        leftCost = frontierCost(leftChildLocation);
        rightCost = frontierCost(rightChildLocation);
        leftStateIndex = double(frontierStateIndex(leftChildLocation));
        rightStateIndex = double(frontierStateIndex(rightChildLocation));
        rightPrecedesLeft = rightCost < leftCost || ( ...
            rightCost == leftCost && rightStateIndex < leftStateIndex);
        if rightPrecedesLeft
            minimumChildLocation = rightChildLocation;
        end
    end

    currentCost = frontierCost(frontierLocation);
    childCost = frontierCost(minimumChildLocation);
    currentStateIndex = double(frontierStateIndex(frontierLocation));
    childStateIndex = double(frontierStateIndex(minimumChildLocation));
    currentPrecedesChild = currentCost < childCost || ( ...
        currentCost == childCost && currentStateIndex < childStateIndex);
    if currentPrecedesChild
        break;
    end

    frontierStateIndex([frontierLocation, minimumChildLocation]) = ...
        frontierStateIndex([minimumChildLocation, frontierLocation]);
    frontierCost([frontierLocation, minimumChildLocation]) = ...
        frontierCost([minimumChildLocation, frontierLocation]);
    frontierLocationByStateIndex(childStateIndex) = ...
        uint32(frontierLocation);
    frontierLocationByStateIndex(currentStateIndex) = ...
        uint32(minimumChildLocation);
    frontierLocation = minimumChildLocation;
end
end

function trajectoryStateIndices = reconstructSimpleDijkstraParents( ...
        parentStateIndex, destinationStateIndex)
%% Section 0: Header & Readme
% SYNTAX
%   indices = reconstructSimpleDijkstraParents(parents, destinationIndex)
%**************************************************************************
% PURPOSE
%   - Follow stored parents from the destination back to the initial state.
%**************************************************************************
% INPUTS
%   - parentStateIndex (numeric vector)
%       Zero identifies the initial root.
%   - destinationStateIndex (positive integer)
%       Terminal generated-state row.
%**************************************************************************
% OUTPUTS
%   - trajectoryStateIndices (numeric column vector)
%       Initial-to-destination generated-state rows.
%**************************************************************************
% UNITS
%   - Indices are dimensionless.
trajectoryStateIndices = zeros(numel(parentStateIndex), 1);
writeIndex = numel(parentStateIndex);
currentStateIndex = destinationStateIndex;
while currentStateIndex ~= 0
    trajectoryStateIndices(writeIndex) = currentStateIndex;
    writeIndex = writeIndex - 1;
    currentStateIndex = double(parentStateIndex(currentStateIndex));
end
trajectoryStateIndices = trajectoryStateIndices(writeIndex + 1:end);
end

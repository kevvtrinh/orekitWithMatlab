function plan = planSimpleAzElTimeKinodynamicDijkstra( ...
        azElData, initialState, destinationState, limits, options)
%% Section 0: Header & Readme
% SYNTAX
%   options = planSimpleAzElTimeKinodynamicDijkstra()
%   plan = planSimpleAzElTimeKinodynamicDijkstra( ...
%       azElData, initialState, destinationState, limits)
%   plan = planSimpleAzElTimeKinodynamicDijkstra( ...
%       azElData, initialState, destinationState, limits, options)
%**************************************************************************
% PURPOSE
%   - Teach a first-principles Dijkstra search over discretized azimuth,
%     elevation, time, velocity, and acceleration.
%   - Apply one constant azimuth/elevation jerk command per time step.
%   - Check every transition against time-varying azElData polygons.
%**************************************************************************
% INPUTS
%   - azElData (struct array or cell array)
%       Canonical moving obstacle data accepted by
%       buildAzElTimeObstacleField.
%   - initialState (scalar struct)
%       .time_s, .position_deg, .velocity_deg_s, and
%       .acceleration_deg_s2 describe the initial kinodynamic state.
%   - destinationState (scalar struct)
%       Same fields as initialState. Its time is an exact terminal time,
%       within options.timeTolerance_s.
%   - limits (scalar struct)
%       .azimuth_deg and .elevation_deg contain axis bounds.
%       .maxVelocity_deg_s, .maxAcceleration_deg_s2, and
%       .maxJerk_deg_s3 contain [azimuth elevation] magnitudes.
%   - options (scalar struct)
%       .timeStep_s sets the uniform time step.
%       .timeStepSchedule_s optionally runs coarse-to-fine time lattices.
%       .positionStep_deg, .velocityStep_deg_s, and
%       .accelerationStep_deg_s2 set the two-axis lattice spacing.
%       .positionStepSchedule_deg optionally runs coarse-to-fine position
%       lattices such as [4 2 1 0.5].
%       .jerkCommands_deg_s3 optionally supplies an N-by-2 command set.
%       .jerkCommandMode is "maximum" for baseline controls or
%       "latticeCompatible" for acceleration-cell-aligned default jerk.
%       .allowAzimuthWrap enables a complete 360-degree azimuth domain.
%       .collisionCheckStep_s and .collisionQueryOptions configure
%       transition sampling and polygon queries.
%       .frontierMethod is "scan" for the original visible minimum scan or
%       "binaryHeap" for the stable indexed priority-queue feature.
%       .equalCostTieBreaker is "stateIndex" for baseline ordering or
%       "destinationDistance" to order only exactly equal-cost scan states.
%       .pruneNonterminalFinalStates discards states on the exact final time
%       slice that do not satisfy the complete destination tolerances.
%       .pruneDynamicallyUnreachableStates uses an obstacle-free backward
%       lattice table to remove states with no remaining jerk sequence.
%       .positionTolerance_deg, .velocityTolerance_deg_s,
%       .accelerationTolerance_deg_s2, and .timeTolerance_s configure the
%       exact-time destination test.
%       .waitingTolerance_deg identifies unchanged position samples.
%       .accelerationWeight and .jerkWeight add nonnegative cost terms.
%       .maximumOccupancyCells, .maximumGeneratedStates, and
%       .maximumExpandedStates limit allocation and search work.
%       .maximumObstacleVerticesPerRegion limits packed polygon vertices;
%       Inf preserves the supplied obstacle boundaries exactly.
%**************************************************************************
% OUTPUTS
%   - plan (scalar struct)
%       .success, .message, and .totalCost summarize the result.
%       .time_s, .position_deg, .positionUnwrapped_deg, .velocity_deg_s,
%       .acceleration_deg_s2, .jerk_deg_s3, and .isWaiting describe the
%       reconstructed timed kinodynamic trajectory.
%       .bestKnownCost, .parentStateIndex, .parentJerk_deg_s3, and the
%       generated-state arrays expose the Dijkstra search.
%       .gridRefinement contains PascalCase per-level diagnostics.
%       State subscripts use [azimuth, elevation, time, azimuth velocity,
%       elevation velocity, azimuth acceleration, elevation acceleration].
%**************************************************************************
% UNITS
%   - Angles are degrees. Time is seconds. Velocity, acceleration, and jerk
%     use deg/s, deg/s^2, and deg/s^3, respectively.

%% Section 1: Validate Inputs
defaultOptions = defaultSimpleDijkstraOptions();
if nargin == 0
    plan = defaultOptions;
    return;
end
if nargin < 5 || isempty(options)
    options = struct();
end
limits = normalizeSimpleDijkstraLimits(limits);
initialState = normalizeSimpleDijkstraState(initialState, "initialState");
destinationState = normalizeSimpleDijkstraState( ...
    destinationState, "destinationState");

if destinationState.time_s < initialState.time_s
    error("planSimpleAzElTimeKinodynamicDijkstra:InvalidTimeOrder", ...
        "destinationState.time_s must not precede initialState.time_s.");
end
endpointStates = [initialState, destinationState];
endpointNames = ["initialState", "destinationState"];
for endpointIndex = 1:numel(endpointStates)
    endpointState = endpointStates(endpointIndex);
    elevationIsInsideLimits = ...
        endpointState.position_deg(2) >= limits.elevation_deg(1) && ...
        endpointState.position_deg(2) <= limits.elevation_deg(2);
    azimuthIsInsideLimits = ...
        endpointState.position_deg(1) >= limits.azimuth_deg(1) && ...
        endpointState.position_deg(1) <= limits.azimuth_deg(2);
    dynamicsAreInsideLimits = ...
        all(abs(endpointState.velocity_deg_s) <= ...
        limits.maxVelocity_deg_s) && ...
        all(abs(endpointState.acceleration_deg_s2) <= ...
        limits.maxAcceleration_deg_s2);
    if ~elevationIsInsideLimits || ~azimuthIsInsideLimits || ...
            ~dynamicsAreInsideLimits
        error("planSimpleAzElTimeKinodynamicDijkstra:EndpointOutsideLimits", ...
            "%s violates a position, velocity, or acceleration limit.", ...
            endpointNames(endpointIndex));
    end
end

%% Section 2: Resolve Grid And Kinodynamic Options
options = resolveSimpleDijkstraOptions(options, defaultOptions, limits);
if ~isempty(options.timeStepSchedule_s)
    plan = runSimpleDijkstraTimeRefinement( ...
        azElData, initialState, destinationState, limits, options);
    return;
end
if ~isempty(options.positionStepSchedule_deg)
    plan = runSimpleDijkstraGridRefinement( ...
        azElData, initialState, destinationState, limits, options);
    return;
end
timeStep_s = options.timeStep_s;
requestedDuration_s = ...
    destinationState.time_s - initialState.time_s;
timeStepCount = round(requestedDuration_s / timeStep_s);
mappedDuration_s = timeStepCount * timeStep_s;
if abs(mappedDuration_s - requestedDuration_s) > options.timeTolerance_s
    error("planSimpleAzElTimeKinodynamicDijkstra:TimeGridMismatch", ...
        ["The exact destination time must map to the uniform time grid " ...
        "within options.timeTolerance_s."]);
end
timeGrid_s = initialState.time_s + (0:timeStepCount).' * timeStep_s;

obstacleFieldOptions = struct( ...
    "MaximumVerticesPerRegion", ...
    options.maximumObstacleVerticesPerRegion);
obstacleField = buildAzElTimeObstacleField( ...
    azElData, obstacleFieldOptions);
% This tolerance absorbs arithmetic noise at exact configured limits. It is
% far below every default lattice step and therefore cannot admit a new cell.
limitTolerance = 1e-12;

%% Section 3: Build The Azimuth Elevation Time Occupancy
azimuthSpan_deg = diff(limits.azimuth_deg);
azimuthStepCount = round(azimuthSpan_deg / options.positionStep_deg(1));
if options.allowAzimuthWrap
    % The upper seam endpoint is omitted because it represents the same
    % direction as the lower endpoint. This avoids duplicate wrapped states.
    azimuthGrid_deg = limits.azimuth_deg(1) + ...
        (0:azimuthStepCount - 1) * options.positionStep_deg(1);
else
    azimuthGrid_deg = limits.azimuth_deg(1) + ...
        (0:azimuthStepCount) * options.positionStep_deg(1);
end
elevationStepCount = round( ...
    diff(limits.elevation_deg) / options.positionStep_deg(2));
elevationGrid_deg = limits.elevation_deg(1) + ...
    (0:elevationStepCount) * options.positionStep_deg(2);

occupancyCellCount = numel(azimuthGrid_deg) * ...
    numel(elevationGrid_deg) * numel(timeGrid_s);
if occupancyCellCount > options.maximumOccupancyCells
    error("planSimpleAzElTimeKinodynamicDijkstra:OccupancyTooLarge", ...
        ["The requested occupancy has %d cells; the configured maximum " ...
        "is %d. Increase grid steps or maximumOccupancyCells."], ...
        occupancyCellCount, options.maximumOccupancyCells);
end
[azimuthMesh_deg, elevationMesh_deg] = meshgrid( ...
    azimuthGrid_deg, elevationGrid_deg);
occupancy = false( ...
    numel(elevationGrid_deg), numel(azimuthGrid_deg), numel(timeGrid_s));
for timeIndex = 1:numel(timeGrid_s)
    occupiedAtTime = queryAzElTimeObstacle( ...
        obstacleField, azimuthMesh_deg, elevationMesh_deg, ...
        timeGrid_s(timeIndex), options.collisionQueryOptions);
    occupancy(:, :, timeIndex) = occupiedAtTime;
end

%% Section 4: Build The Discrete State Axes
azimuthVelocityCount = round( ...
    limits.maxVelocity_deg_s(1) / options.velocityStep_deg_s(1));
elevationVelocityCount = round( ...
    limits.maxVelocity_deg_s(2) / options.velocityStep_deg_s(2));
azimuthVelocityGrid_deg_s = ...
    (-azimuthVelocityCount:azimuthVelocityCount) * ...
    options.velocityStep_deg_s(1);
elevationVelocityGrid_deg_s = ...
    (-elevationVelocityCount:elevationVelocityCount) * ...
    options.velocityStep_deg_s(2);

azimuthAccelerationCount = round(limits.maxAcceleration_deg_s2(1) / ...
    options.accelerationStep_deg_s2(1));
elevationAccelerationCount = round(limits.maxAcceleration_deg_s2(2) / ...
    options.accelerationStep_deg_s2(2));
azimuthAccelerationGrid_deg_s2 = ...
    (-azimuthAccelerationCount:azimuthAccelerationCount) * ...
    options.accelerationStep_deg_s2(1);
elevationAccelerationGrid_deg_s2 = ...
    (-elevationAccelerationCount:elevationAccelerationCount) * ...
    options.accelerationStep_deg_s2(2);

% States are generated on demand. One character key encodes the seven
% integer subscripts in the ordering documented in the function header.
% A containers.Map lookup detects every repeated discretized state.

%% Section 5: Map The Initial And Destination States
if options.allowAzimuthWrap
    initialAzimuthDifference_deg = mod(azimuthGrid_deg - ...
        initialState.position_deg(1) + 180, 360) - 180;
    destinationAzimuthDifference_deg = mod(azimuthGrid_deg - ...
        destinationState.position_deg(1) + 180, 360) - 180;
else
    initialAzimuthDifference_deg = ...
        azimuthGrid_deg - initialState.position_deg(1);
    destinationAzimuthDifference_deg = ...
        azimuthGrid_deg - destinationState.position_deg(1);
end
[~, initialAzimuthIndex] = min(abs(initialAzimuthDifference_deg));
[~, destinationAzimuthIndex] = min(abs(destinationAzimuthDifference_deg));
[~, initialElevationIndex] = min(abs( ...
    elevationGrid_deg - initialState.position_deg(2)));
[~, destinationElevationIndex] = min(abs( ...
    elevationGrid_deg - destinationState.position_deg(2)));
[~, initialAzimuthVelocityIndex] = min(abs( ...
    azimuthVelocityGrid_deg_s - initialState.velocity_deg_s(1)));
[~, initialElevationVelocityIndex] = min(abs( ...
    elevationVelocityGrid_deg_s - initialState.velocity_deg_s(2)));
[~, destinationAzimuthVelocityIndex] = min(abs( ...
    azimuthVelocityGrid_deg_s - destinationState.velocity_deg_s(1)));
[~, destinationElevationVelocityIndex] = min(abs( ...
    elevationVelocityGrid_deg_s - destinationState.velocity_deg_s(2)));
[~, initialAzimuthAccelerationIndex] = min(abs( ...
    azimuthAccelerationGrid_deg_s2 - ...
    initialState.acceleration_deg_s2(1)));
[~, initialElevationAccelerationIndex] = min(abs( ...
    elevationAccelerationGrid_deg_s2 - ...
    initialState.acceleration_deg_s2(2)));
[~, destinationAzimuthAccelerationIndex] = min(abs( ...
    azimuthAccelerationGrid_deg_s2 - ...
    destinationState.acceleration_deg_s2(1)));
[~, destinationElevationAccelerationIndex] = min(abs( ...
    elevationAccelerationGrid_deg_s2 - ...
    destinationState.acceleration_deg_s2(2)));

initialSubscripts = [ ...
    initialAzimuthIndex, initialElevationIndex, 1, ...
    initialAzimuthVelocityIndex, initialElevationVelocityIndex, ...
    initialAzimuthAccelerationIndex, initialElevationAccelerationIndex];
destinationSubscripts = [ ...
    destinationAzimuthIndex, destinationElevationIndex, numel(timeGrid_s), ...
    destinationAzimuthVelocityIndex, destinationElevationVelocityIndex, ...
    destinationAzimuthAccelerationIndex, ...
    destinationElevationAccelerationIndex];

mappedInitialPosition_deg = [ ...
    azimuthGrid_deg(initialAzimuthIndex), ...
    elevationGrid_deg(initialElevationIndex)];
mappedInitialVelocity_deg_s = [ ...
    azimuthVelocityGrid_deg_s(initialAzimuthVelocityIndex), ...
    elevationVelocityGrid_deg_s(initialElevationVelocityIndex)];
mappedInitialAcceleration_deg_s2 = [ ...
    azimuthAccelerationGrid_deg_s2(initialAzimuthAccelerationIndex), ...
    elevationAccelerationGrid_deg_s2(initialElevationAccelerationIndex)];
mappedDestinationPosition_deg = [ ...
    azimuthGrid_deg(destinationAzimuthIndex), ...
    elevationGrid_deg(destinationElevationIndex)];
mappedDestinationVelocity_deg_s = [ ...
    azimuthVelocityGrid_deg_s(destinationAzimuthVelocityIndex), ...
    elevationVelocityGrid_deg_s(destinationElevationVelocityIndex)];
mappedDestinationAcceleration_deg_s2 = [ ...
    azimuthAccelerationGrid_deg_s2(destinationAzimuthAccelerationIndex), ...
    elevationAccelerationGrid_deg_s2(destinationElevationAccelerationIndex)];

if occupancy(initialElevationIndex, initialAzimuthIndex, 1)
    error("planSimpleAzElTimeKinodynamicDijkstra:InitialStateOccupied", ...
        "The mapped initial state is occupied.");
end
if occupancy(destinationElevationIndex, destinationAzimuthIndex, end)
    error("planSimpleAzElTimeKinodynamicDijkstra:DestinationStateOccupied", ...
        "The mapped destination state is occupied.");
end
specifiedInitialStateIsOccupied = queryAzElTimeObstacle( ...
    obstacleField, initialState.position_deg(1), ...
    initialState.position_deg(2), initialState.time_s, ...
    options.collisionQueryOptions);
specifiedDestinationStateIsOccupied = queryAzElTimeObstacle( ...
    obstacleField, destinationState.position_deg(1), ...
    destinationState.position_deg(2), destinationState.time_s, ...
    options.collisionQueryOptions);
if specifiedInitialStateIsOccupied
    error("planSimpleAzElTimeKinodynamicDijkstra:InitialStateOccupied", ...
        "The specified initial state is occupied.");
end
if specifiedDestinationStateIsOccupied
    error("planSimpleAzElTimeKinodynamicDijkstra:DestinationStateOccupied", ...
        "The specified destination state is occupied.");
end

%% Section 6: Define The Discrete Jerk Commands
if isempty(options.jerkCommands_deg_s3)
    if options.jerkCommandMode == "maximum"
        jerkMagnitude_deg_s3 = limits.maxJerk_deg_s3;
    else
        accelerationCellsPerMaximumJerk = floor( ...
            limits.maxJerk_deg_s3 * timeStep_s ./ ...
            options.accelerationStep_deg_s2 + limitTolerance);
        jerkMagnitude_deg_s3 = accelerationCellsPerMaximumJerk .* ...
            options.accelerationStep_deg_s2 / timeStep_s;
    end
    azimuthJerkValues_deg_s3 = unique( ...
        [-jerkMagnitude_deg_s3(1), 0, jerkMagnitude_deg_s3(1)], ...
        "stable");
    elevationJerkValues_deg_s3 = unique( ...
        [-jerkMagnitude_deg_s3(2), 0, jerkMagnitude_deg_s3(2)], ...
        "stable");
    [azimuthJerkMesh_deg_s3, elevationJerkMesh_deg_s3] = ndgrid( ...
        azimuthJerkValues_deg_s3, elevationJerkValues_deg_s3);
    jerkCommands_deg_s3 = [ ...
        azimuthJerkMesh_deg_s3(:), elevationJerkMesh_deg_s3(:)];
else
    jerkCommands_deg_s3 = options.jerkCommands_deg_s3;
end
jerkCommands_deg_s3 = unique(jerkCommands_deg_s3, "rows", "stable");

if options.pruneDynamicallyUnreachableStates
    azimuthCanReachDestination = ...
        buildSimpleDijkstraAxisBackwardReachability( ...
        azimuthGrid_deg, azimuthVelocityGrid_deg_s, ...
        azimuthAccelerationGrid_deg_s2, ...
        unique(jerkCommands_deg_s3(:, 1), "stable"), ...
        timeStep_s, timeStepCount, ...
        destinationState.position_deg(1), ...
        destinationState.velocity_deg_s(1), ...
        destinationState.acceleration_deg_s2(1), ...
        options.positionTolerance_deg(1), ...
        options.velocityTolerance_deg_s(1), ...
        options.accelerationTolerance_deg_s2(1), ...
        limits.azimuth_deg, limits.maxVelocity_deg_s(1), ...
        limits.maxAcceleration_deg_s2(1), options.allowAzimuthWrap);
    elevationCanReachDestination = ...
        buildSimpleDijkstraAxisBackwardReachability( ...
        elevationGrid_deg, elevationVelocityGrid_deg_s, ...
        elevationAccelerationGrid_deg_s2, ...
        unique(jerkCommands_deg_s3(:, 2), "stable"), ...
        timeStep_s, timeStepCount, ...
        destinationState.position_deg(2), ...
        destinationState.velocity_deg_s(2), ...
        destinationState.acceleration_deg_s2(2), ...
        options.positionTolerance_deg(2), ...
        options.velocityTolerance_deg_s(2), ...
        options.accelerationTolerance_deg_s2(2), ...
        limits.elevation_deg, limits.maxVelocity_deg_s(2), ...
        limits.maxAcceleration_deg_s2(2), false);
else
    azimuthCanReachDestination = false(0, 0, 0, 0);
    elevationCanReachDestination = false(0, 0, 0, 0);
end

%% Section 7: Initialize Dijkstra
maximumGeneratedStates = options.maximumGeneratedStates;
stateSubscripts = zeros(maximumGeneratedStates, 7, "uint32");
statePosition_deg = nan(maximumGeneratedStates, 2);
stateVelocity_deg_s = nan(maximumGeneratedStates, 2);
stateAcceleration_deg_s2 = nan(maximumGeneratedStates, 2);
stateTime_s = nan(maximumGeneratedStates, 1);

% The three lines below are the recognizable Dijkstra initialization.
bestKnownCost = inf(maximumGeneratedStates, 1);
parentStateIndex = zeros(maximumGeneratedStates, 1, "uint32");
parentJerk_deg_s3 = nan(maximumGeneratedStates, 2);
isSettled = false(maximumGeneratedStates, 1);

generatedStateCount = 1;
stateSubscripts(1, :) = uint32(initialSubscripts);
statePosition_deg(1, :) = mappedInitialPosition_deg;
stateVelocity_deg_s(1, :) = mappedInitialVelocity_deg_s;
stateAcceleration_deg_s2(1, :) = mappedInitialAcceleration_deg_s2;
stateTime_s(1) = timeGrid_s(1);
bestKnownCost(1) = 0;
parentJerk_deg_s3(1, :) = [0, 0];

initialStateKey = sprintf("%d|%d|%d|%d|%d|%d|%d", initialSubscripts);
stateIndexByKey = containers.Map( ...
    "KeyType", "char", "ValueType", "double");
stateIndexByKey(initialStateKey) = 1;
destinationStateIndex = 0;
expandedStateCount = 0;
dynamicReachabilityPrunedStateCount = 0;
reachedGeneratedStateLimit = false;
reachedExpandedStateLimit = false;

% The optional heap stores one entry per unsettled generated state. Its
% reverse-location array supports an in-place decrease-key operation, so
% stale duplicate entries never consume the configured state budget.
frontierStateIndex = zeros(maximumGeneratedStates, 1, "uint32");
frontierCost = inf(maximumGeneratedStates, 1);
frontierLocationByStateIndex = zeros( ...
    maximumGeneratedStates, 1, "uint32");
frontierCount = 0;
if options.frontierMethod == "binaryHeap"
    [frontierStateIndex, frontierCost, ...
        frontierLocationByStateIndex, frontierCount] = ...
        pushOrDecreaseSimpleDijkstraFrontier( ...
        frontierStateIndex, frontierCost, ...
        frontierLocationByStateIndex, frontierCount, 1, 0);
end

%% Section 8: Propagate Candidate Kinodynamic States
while true
    if options.frontierMethod == "scan"
        unsettledStateIndices = find( ...
            ~isSettled(1:generatedStateCount) & ...
            isfinite(bestKnownCost(1:generatedStateCount)));
        if isempty(unsettledStateIndices)
            break;
        end

        % The original minimum scan remains visible and selectable.
        unsettledCosts = bestKnownCost(unsettledStateIndices);
        minimumCost = min(unsettledCosts);
        minimumCostLocations = find(unsettledCosts == minimumCost);
        if options.equalCostTieBreaker == "destinationDistance" && ...
                numel(minimumCostLocations) > 1
            equalCostStateIndices = ...
                unsettledStateIndices(minimumCostLocations);
            equalCostPosition_deg = ...
                statePosition_deg(equalCostStateIndices, :);
            equalCostVelocity_deg_s = ...
                stateVelocity_deg_s(equalCostStateIndices, :);
            equalCostAcceleration_deg_s2 = ...
                stateAcceleration_deg_s2(equalCostStateIndices, :);
            azimuthError_deg = mod(destinationState.position_deg(1) - ...
                equalCostPosition_deg(:, 1) + 180, 360) - 180;
            if ~options.allowAzimuthWrap
                azimuthError_deg = destinationState.position_deg(1) - ...
                    equalCostPosition_deg(:, 1);
            end
            positionError_deg = [ ...
                azimuthError_deg, destinationState.position_deg(2) - ...
                equalCostPosition_deg(:, 2)];
            velocityError_deg_s = destinationState.velocity_deg_s - ...
                equalCostVelocity_deg_s;
            accelerationError_deg_s2 = ...
                destinationState.acceleration_deg_s2 - ...
                equalCostAcceleration_deg_s2;
            tieBreakScore = sum((positionError_deg ./ ...
                options.positionStep_deg).^2, 2) + ...
                sum((velocityError_deg_s ./ ...
                options.velocityStep_deg_s).^2, 2) + ...
                sum((accelerationError_deg_s2 ./ ...
                options.accelerationStep_deg_s2).^2, 2);
            [~, equalCostChoice] = min(tieBreakScore);
            minimumCostLocation = ...
                minimumCostLocations(equalCostChoice);
        else
            minimumCostLocation = minimumCostLocations(1);
        end
        currentStateIndex = unsettledStateIndices(minimumCostLocation);
    else
        [currentStateIndex, frontierStateIndex, frontierCost, ...
            frontierLocationByStateIndex, frontierCount] = ...
            popSimpleDijkstraFrontier( ...
            frontierStateIndex, frontierCost, ...
            frontierLocationByStateIndex, frontierCount);
        if currentStateIndex == 0
            break;
        end
    end
    isSettled(currentStateIndex) = true;
    expandedStateCount = expandedStateCount + 1;

    currentPosition_deg = statePosition_deg(currentStateIndex, :);
    currentVelocity_deg_s = stateVelocity_deg_s(currentStateIndex, :);
    currentAcceleration_deg_s2 = ...
        stateAcceleration_deg_s2(currentStateIndex, :);
    currentTime_s = stateTime_s(currentStateIndex);
    currentTimeIndex = double(stateSubscripts(currentStateIndex, 3));

    % The terminal tolerances apply to the specified destination, not its
    % nearest grid proxy. A coarse level therefore fails honestly when it
    % cannot represent the requested endpoint closely enough.
    azimuthError_deg = mod(destinationState.position_deg(1) - ...
        currentPosition_deg(1) + 180, 360) - 180;
    if ~options.allowAzimuthWrap
        azimuthError_deg = destinationState.position_deg(1) - ...
            currentPosition_deg(1);
    end
    positionError_deg = [ ...
        azimuthError_deg, ...
        destinationState.position_deg(2) - currentPosition_deg(2)];
    velocityError_deg_s = ...
        destinationState.velocity_deg_s - currentVelocity_deg_s;
    accelerationError_deg_s2 = ...
        destinationState.acceleration_deg_s2 - ...
        currentAcceleration_deg_s2;
    timeError_s = destinationState.time_s - currentTime_s;

    isDestinationState = ...
        all(abs(positionError_deg) <= options.positionTolerance_deg) && ...
        all(abs(velocityError_deg_s) <= options.velocityTolerance_deg_s) && ...
        all(abs(accelerationError_deg_s2) <= ...
        options.accelerationTolerance_deg_s2) && ...
        abs(timeError_s) <= options.timeTolerance_s;
    if isDestinationState
        destinationStateIndex = currentStateIndex;
        break;
    end
    if expandedStateCount >= options.maximumExpandedStates
        reachedExpandedStateLimit = true;
        break;
    end
    if currentTimeIndex >= numel(timeGrid_s)
        continue;
    end

    for jerkCommandIndex = 1:size(jerkCommands_deg_s3, 1)
        appliedJerk_deg_s3 = jerkCommands_deg_s3(jerkCommandIndex, :);

        % One constant jerk command propagates acceleration, then velocity,
        % then position independently on the two axes.
        nextAcceleration_deg_s2 = currentAcceleration_deg_s2 + ...
            appliedJerk_deg_s3 * timeStep_s;
        nextVelocity_deg_s = currentVelocity_deg_s + ...
            currentAcceleration_deg_s2 * timeStep_s + ...
            0.5 * appliedJerk_deg_s3 * timeStep_s^2;
        propagatedPosition_deg = currentPosition_deg + ...
            currentVelocity_deg_s * timeStep_s + ...
            0.5 * currentAcceleration_deg_s2 * timeStep_s^2 + ...
            (1 / 6) * appliedJerk_deg_s3 * timeStep_s^3;

        % --- Section 9: Check Limits And Collision -----------------------
        % A dashed stage keeps the search loop uninterrupted while making
        % the requested limit and collision responsibility easy to locate.
        dynamicsAreInsideLimits = ...
            all(abs(nextVelocity_deg_s) <= ...
            limits.maxVelocity_deg_s + limitTolerance) && ...
            all(abs(nextAcceleration_deg_s2) <= ...
            limits.maxAcceleration_deg_s2 + limitTolerance);
        elevationIsInsideLimits = ...
            propagatedPosition_deg(2) >= ...
            limits.elevation_deg(1) - limitTolerance && ...
            propagatedPosition_deg(2) <= ...
            limits.elevation_deg(2) + limitTolerance;
        azimuthIsInsideLimits = options.allowAzimuthWrap || ( ...
            propagatedPosition_deg(1) >= ...
            limits.azimuth_deg(1) - limitTolerance && ...
            propagatedPosition_deg(1) <= ...
            limits.azimuth_deg(2) + limitTolerance);

        % Endpoint checks alone are insufficient: quadratic velocity can
        % peak where acceleration crosses zero, and cubic position can turn
        % where velocity crosses zero. Test those analytic interior extrema
        % before accepting the constant-jerk transition.
        for axisIndex = 1:2
            axisJerk_deg_s3 = appliedJerk_deg_s3(axisIndex);
            axisAcceleration_deg_s2 = ...
                currentAcceleration_deg_s2(axisIndex);
            axisVelocity_deg_s = currentVelocity_deg_s(axisIndex);

            if abs(axisJerk_deg_s3) > limitTolerance
                velocityExtremumTime_s = ...
                    -axisAcceleration_deg_s2 / axisJerk_deg_s3;
                velocityExtremumIsInterior = ...
                    velocityExtremumTime_s > 0 && ...
                    velocityExtremumTime_s < timeStep_s;
                if velocityExtremumIsInterior
                    velocityExtremum_deg_s = axisVelocity_deg_s + ...
                        axisAcceleration_deg_s2 * velocityExtremumTime_s + ...
                        0.5 * axisJerk_deg_s3 * velocityExtremumTime_s^2;
                    dynamicsAreInsideLimits = dynamicsAreInsideLimits && ...
                        abs(velocityExtremum_deg_s) <= ...
                        limits.maxVelocity_deg_s(axisIndex) + limitTolerance;
                end
            end

            axisRequiresPositionBounds = ...
                axisIndex == 2 || ~options.allowAzimuthWrap;
            if ~axisRequiresPositionBounds
                continue;
            end
            if axisIndex == 1
                axisPositionLimits_deg = limits.azimuth_deg;
            else
                axisPositionLimits_deg = limits.elevation_deg;
            end

            positionExtremumTimes_s = zeros(2, 1);
            positionExtremumCount = 0;
            if abs(axisJerk_deg_s3) <= limitTolerance
                if abs(axisAcceleration_deg_s2) > limitTolerance
                    positionExtremumCount = 1;
                    positionExtremumTimes_s(1) = ...
                        -axisVelocity_deg_s / axisAcceleration_deg_s2;
                end
            else
                velocityDiscriminant_deg2_s4 = ...
                    axisAcceleration_deg_s2^2 - ...
                    2 * axisJerk_deg_s3 * axisVelocity_deg_s;
                if velocityDiscriminant_deg2_s4 >= 0
                    velocityRootTerm_deg_s2 = ...
                        sqrt(velocityDiscriminant_deg2_s4);
                    positionExtremumCount = 2;
                    positionExtremumTimes_s = [ ...
                        (-axisAcceleration_deg_s2 - ...
                        velocityRootTerm_deg_s2) / axisJerk_deg_s3; ...
                        (-axisAcceleration_deg_s2 + ...
                        velocityRootTerm_deg_s2) / axisJerk_deg_s3];
                end
            end
            for extremumIndex = 1:positionExtremumCount
                positionExtremumTime_s = ...
                    positionExtremumTimes_s(extremumIndex);
                positionExtremumIsInterior = ...
                    positionExtremumTime_s > 0 && ...
                    positionExtremumTime_s < timeStep_s;
                if ~positionExtremumIsInterior
                    continue;
                end
                positionExtremum_deg = currentPosition_deg(axisIndex) + ...
                    axisVelocity_deg_s * positionExtremumTime_s + ...
                    0.5 * axisAcceleration_deg_s2 * ...
                    positionExtremumTime_s^2 + ...
                    (1 / 6) * axisJerk_deg_s3 * ...
                    positionExtremumTime_s^3;
                extremumIsInsidePositionLimits = ...
                    positionExtremum_deg >= ...
                    axisPositionLimits_deg(1) - limitTolerance && ...
                    positionExtremum_deg <= ...
                    axisPositionLimits_deg(2) + limitTolerance;
                if axisIndex == 1
                    azimuthIsInsideLimits = azimuthIsInsideLimits && ...
                        extremumIsInsidePositionLimits;
                else
                    elevationIsInsideLimits = elevationIsInsideLimits && ...
                        extremumIsInsidePositionLimits;
                end
            end
        end
        if ~dynamicsAreInsideLimits || ~elevationIsInsideLimits || ...
                ~azimuthIsInsideLimits
            continue;
        end

        if options.allowAzimuthWrap
            propagatedPosition_deg(1) = mod( ...
                propagatedPosition_deg(1) - limits.azimuth_deg(1), 360) + ...
                limits.azimuth_deg(1);
        end

        % Nearest-axis snapping is the only approximation used to create a
        % finite successor lattice. Its half-cell error bounds are returned
        % in plan.maximumDiscretizationError.
        if options.allowAzimuthWrap
            candidateAzimuthDifference_deg = mod(azimuthGrid_deg - ...
                propagatedPosition_deg(1) + 180, 360) - 180;
        else
            candidateAzimuthDifference_deg = ...
                azimuthGrid_deg - propagatedPosition_deg(1);
        end
        [~, neighborAzimuthIndex] = min( ...
            abs(candidateAzimuthDifference_deg));
        [~, neighborElevationIndex] = min(abs( ...
            elevationGrid_deg - propagatedPosition_deg(2)));
        [~, neighborAzimuthVelocityIndex] = min(abs( ...
            azimuthVelocityGrid_deg_s - nextVelocity_deg_s(1)));
        [~, neighborElevationVelocityIndex] = min(abs( ...
            elevationVelocityGrid_deg_s - nextVelocity_deg_s(2)));
        [~, neighborAzimuthAccelerationIndex] = min(abs( ...
            azimuthAccelerationGrid_deg_s2 - nextAcceleration_deg_s2(1)));
        [~, neighborElevationAccelerationIndex] = min(abs( ...
            elevationAccelerationGrid_deg_s2 - nextAcceleration_deg_s2(2)));
        neighborTimeIndex = currentTimeIndex + 1;

        if options.pruneDynamicallyUnreachableStates
            azimuthIsDynamicallyReachable = ...
                azimuthCanReachDestination( ...
                neighborAzimuthIndex, neighborAzimuthVelocityIndex, ...
                neighborAzimuthAccelerationIndex, neighborTimeIndex);
            elevationIsDynamicallyReachable = ...
                elevationCanReachDestination( ...
                neighborElevationIndex, neighborElevationVelocityIndex, ...
                neighborElevationAccelerationIndex, neighborTimeIndex);
            if ~azimuthIsDynamicallyReachable || ...
                    ~elevationIsDynamicallyReachable
                dynamicReachabilityPrunedStateCount = ...
                    dynamicReachabilityPrunedStateCount + 1;
                continue;
            end
        end

        % An exact-time nonterminal state on the final slice has no outgoing
        % transition and can never become a solution. Optional pruning here
        % is exact: it applies the same complete terminal test as Section 8
        % before the state consumes generated-state storage.
        if options.pruneNonterminalFinalStates && ...
                neighborTimeIndex == numel(timeGrid_s)
            mappedNeighborPosition_deg = [ ...
                azimuthGrid_deg(neighborAzimuthIndex), ...
                elevationGrid_deg(neighborElevationIndex)];
            mappedNeighborVelocity_deg_s = [ ...
                azimuthVelocityGrid_deg_s( ...
                neighborAzimuthVelocityIndex), ...
                elevationVelocityGrid_deg_s( ...
                neighborElevationVelocityIndex)];
            mappedNeighborAcceleration_deg_s2 = [ ...
                azimuthAccelerationGrid_deg_s2( ...
                neighborAzimuthAccelerationIndex), ...
                elevationAccelerationGrid_deg_s2( ...
                neighborElevationAccelerationIndex)];
            terminalAzimuthError_deg = mod( ...
                destinationState.position_deg(1) - ...
                mappedNeighborPosition_deg(1) + 180, 360) - 180;
            if ~options.allowAzimuthWrap
                terminalAzimuthError_deg = ...
                    destinationState.position_deg(1) - ...
                    mappedNeighborPosition_deg(1);
            end
            terminalPositionError_deg = [ ...
                terminalAzimuthError_deg, ...
                destinationState.position_deg(2) - ...
                mappedNeighborPosition_deg(2)];
            terminalVelocityError_deg_s = ...
                destinationState.velocity_deg_s - ...
                mappedNeighborVelocity_deg_s;
            terminalAccelerationError_deg_s2 = ...
                destinationState.acceleration_deg_s2 - ...
                mappedNeighborAcceleration_deg_s2;
            neighborSatisfiesDestination = all(abs( ...
                terminalPositionError_deg) <= ...
                options.positionTolerance_deg) && all(abs( ...
                terminalVelocityError_deg_s) <= ...
                options.velocityTolerance_deg_s) && all(abs( ...
                terminalAccelerationError_deg_s2) <= ...
                options.accelerationTolerance_deg_s2);
            if ~neighborSatisfiesDestination
                continue;
            end
        end

        if occupancy(neighborElevationIndex, neighborAzimuthIndex, ...
                neighborTimeIndex)
            continue;
        end
        transitionIsBlocked = simpleDijkstraTransitionHasCollision( ...
            obstacleField, currentPosition_deg, currentVelocity_deg_s, ...
            currentAcceleration_deg_s2, appliedJerk_deg_s3, ...
            currentTime_s, timeStep_s, options.collisionCheckStep_s, ...
            limits, options);
        if transitionIsBlocked
            continue;
        end

        neighborSubscripts = [ ...
            neighborAzimuthIndex, neighborElevationIndex, ...
            neighborTimeIndex, neighborAzimuthVelocityIndex, ...
            neighborElevationVelocityIndex, ...
            neighborAzimuthAccelerationIndex, ...
            neighborElevationAccelerationIndex];
        neighborStateKey = sprintf( ...
            "%d|%d|%d|%d|%d|%d|%d", neighborSubscripts);

        if isKey(stateIndexByKey, neighborStateKey)
            neighborStateIndex = stateIndexByKey(neighborStateKey);
        else
            if generatedStateCount >= maximumGeneratedStates
                reachedGeneratedStateLimit = true;
                break;
            end
            generatedStateCount = generatedStateCount + 1;
            neighborStateIndex = generatedStateCount;
            stateIndexByKey(neighborStateKey) = neighborStateIndex;
            stateSubscripts(neighborStateIndex, :) = ...
                uint32(neighborSubscripts);
            statePosition_deg(neighborStateIndex, :) = [ ...
                azimuthGrid_deg(neighborAzimuthIndex), ...
                elevationGrid_deg(neighborElevationIndex)];
            stateVelocity_deg_s(neighborStateIndex, :) = [ ...
                azimuthVelocityGrid_deg_s(neighborAzimuthVelocityIndex), ...
                elevationVelocityGrid_deg_s( ...
                neighborElevationVelocityIndex)];
            stateAcceleration_deg_s2(neighborStateIndex, :) = [ ...
                azimuthAccelerationGrid_deg_s2( ...
                neighborAzimuthAccelerationIndex), ...
                elevationAccelerationGrid_deg_s2( ...
                neighborElevationAccelerationIndex)];
            stateTime_s(neighborStateIndex) = ...
                timeGrid_s(neighborTimeIndex);
        end

        % --- Section 10: Relax Dijkstra Costs ----------------------------
        transitionCost = timeStep_s + ...
            options.accelerationWeight * ...
            sum(nextAcceleration_deg_s2.^2) * timeStep_s + ...
            options.jerkWeight * sum(appliedJerk_deg_s3.^2) * timeStep_s;
        currentCost = bestKnownCost(currentStateIndex);
        candidateCost = currentCost + transitionCost;

        if candidateCost < bestKnownCost(neighborStateIndex)
            bestKnownCost(neighborStateIndex) = candidateCost;
            parentStateIndex(neighborStateIndex) = ...
                uint32(currentStateIndex);
            parentJerk_deg_s3(neighborStateIndex, :) = ...
                appliedJerk_deg_s3;
            if options.frontierMethod == "binaryHeap"
                [frontierStateIndex, frontierCost, ...
                    frontierLocationByStateIndex, frontierCount] = ...
                    pushOrDecreaseSimpleDijkstraFrontier( ...
                    frontierStateIndex, frontierCost, ...
                    frontierLocationByStateIndex, frontierCount, ...
                    neighborStateIndex, candidateCost);
            end
        end
    end
    if reachedGeneratedStateLimit
        break;
    end
end

%% Section 11: Reconstruct The Trajectory
if destinationStateIndex > 0
    trajectoryStateIndices = reconstructSimpleDijkstraParents( ...
        parentStateIndex, destinationStateIndex);
    trajectoryTime_s = stateTime_s(trajectoryStateIndices);
    trajectoryPosition_deg = statePosition_deg(trajectoryStateIndices, :);
    trajectoryVelocity_deg_s = ...
        stateVelocity_deg_s(trajectoryStateIndices, :);
    trajectoryAcceleration_deg_s2 = ...
        stateAcceleration_deg_s2(trajectoryStateIndices, :);
    trajectoryJerk_deg_s3 = parentJerk_deg_s3(trajectoryStateIndices, :);

    trajectoryPositionUnwrapped_deg = trajectoryPosition_deg;
    for trajectoryIndex = 2:numel(trajectoryStateIndices)
        wrappedAzimuthStep_deg = mod( ...
            trajectoryPosition_deg(trajectoryIndex, 1) - ...
            trajectoryPosition_deg(trajectoryIndex - 1, 1) + 180, 360) - 180;
        trajectoryPositionUnwrapped_deg(trajectoryIndex, 1) = ...
            trajectoryPositionUnwrapped_deg(trajectoryIndex - 1, 1) + ...
            wrappedAzimuthStep_deg;
    end

    trajectoryIsWaiting = false(numel(trajectoryStateIndices), 1);
    % This dynamics tolerance only absorbs floating-point zero; position
    % equality remains governed by the public waitingTolerance_deg option.
    holdDynamicsTolerance = 1e-12;
    for trajectoryIndex = 2:numel(trajectoryStateIndices)
        previousIndex = trajectoryIndex - 1;
        wrappedPositionChange_deg = mod( ...
            trajectoryPosition_deg(trajectoryIndex, 1) - ...
            trajectoryPosition_deg(previousIndex, 1) + 180, 360) - 180;
        positionDidNotChange = ...
            abs(wrappedPositionChange_deg) <= options.waitingTolerance_deg && ...
            abs(trajectoryPosition_deg(trajectoryIndex, 2) - ...
            trajectoryPosition_deg(previousIndex, 2)) <= ...
            options.waitingTolerance_deg;
        dynamicsDescribeTrueHold = all(abs( ...
            trajectoryVelocity_deg_s(previousIndex, :)) <= ...
            holdDynamicsTolerance) && ...
            all(abs(trajectoryAcceleration_deg_s2(previousIndex, :)) <= ...
            holdDynamicsTolerance) && all(abs( ...
            trajectoryJerk_deg_s3(trajectoryIndex, :)) <= ...
            holdDynamicsTolerance);
        trajectoryIsWaiting(trajectoryIndex) = ...
            positionDidNotChange && dynamicsDescribeTrueHold;
    end
else
    trajectoryStateIndices = zeros(0, 1);
    trajectoryTime_s = zeros(0, 1);
    trajectoryPosition_deg = zeros(0, 2);
    trajectoryPositionUnwrapped_deg = zeros(0, 2);
    trajectoryVelocity_deg_s = zeros(0, 2);
    trajectoryAcceleration_deg_s2 = zeros(0, 2);
    trajectoryJerk_deg_s3 = zeros(0, 2);
    trajectoryIsWaiting = false(0, 1);
end

%% Section 12: Package The Result
if destinationStateIndex > 0
    success = true;
    message = "Exact-time kinodynamic Dijkstra trajectory found.";
    totalCost = bestKnownCost(destinationStateIndex);
elseif reachedGeneratedStateLimit
    success = false;
    message = "Search reached options.maximumGeneratedStates.";
    totalCost = Inf;
elseif reachedExpandedStateLimit
    success = false;
    message = "Search reached options.maximumExpandedStates.";
    totalCost = Inf;
else
    success = false;
    message = "No discretized kinodynamic trajectory reaches the destination.";
    totalCost = Inf;
end

generatedRange = 1:generatedStateCount;
plan = struct( ...
    "success", success, ...
    "message", message, ...
    "time_s", trajectoryTime_s, ...
    "position_deg", trajectoryPosition_deg, ...
    "positionUnwrapped_deg", trajectoryPositionUnwrapped_deg, ...
    "velocity_deg_s", trajectoryVelocity_deg_s, ...
    "acceleration_deg_s2", trajectoryAcceleration_deg_s2, ...
    "jerk_deg_s3", trajectoryJerk_deg_s3, ...
    "isWaiting", trajectoryIsWaiting, ...
    "stateIndices", trajectoryStateIndices, ...
    "totalCost", totalCost, ...
    "expandedStateCount", expandedStateCount, ...
    "generatedStateCount", generatedStateCount, ...
    "frontierMethod", options.frontierMethod, ...
    "equalCostTieBreaker", options.equalCostTieBreaker, ...
    "dynamicReachabilityPrunedStateCount", ...
    dynamicReachabilityPrunedStateCount, ...
    "azimuthGrid_deg", azimuthGrid_deg, ...
    "elevationGrid_deg", elevationGrid_deg, ...
    "timeGrid_s", timeGrid_s, ...
    "azimuthVelocityGrid_deg_s", azimuthVelocityGrid_deg_s, ...
    "elevationVelocityGrid_deg_s", elevationVelocityGrid_deg_s, ...
    "azimuthAccelerationGrid_deg_s2", ...
    azimuthAccelerationGrid_deg_s2, ...
    "elevationAccelerationGrid_deg_s2", ...
    elevationAccelerationGrid_deg_s2, ...
    "jerkCommands_deg_s3", jerkCommands_deg_s3, ...
    "occupancy", occupancy, ...
    "settledStateIndices", find(isSettled(generatedRange)), ...
    "bestKnownCost", bestKnownCost(generatedRange), ...
    "parentStateIndex", parentStateIndex(generatedRange), ...
    "parentJerk_deg_s3", parentJerk_deg_s3(generatedRange, :), ...
    "stateSubscripts", stateSubscripts(generatedRange, :), ...
    "statePosition_deg", statePosition_deg(generatedRange, :), ...
    "stateVelocity_deg_s", stateVelocity_deg_s(generatedRange, :), ...
    "stateAcceleration_deg_s2", ...
    stateAcceleration_deg_s2(generatedRange, :), ...
    "stateTime_s", stateTime_s(generatedRange), ...
    "exactCollisionValidated", false, ...
    "sampledCollisionValidated", success, ...
    "initialState", initialState, ...
    "destinationState", destinationState, ...
    "mappedInitialState", struct( ...
        "Subscripts", initialSubscripts, ...
        "Position_deg", mappedInitialPosition_deg, ...
        "Velocity_deg_s", mappedInitialVelocity_deg_s, ...
        "Acceleration_deg_s2", mappedInitialAcceleration_deg_s2), ...
    "mappedDestinationState", struct( ...
        "Subscripts", destinationSubscripts, ...
        "Position_deg", mappedDestinationPosition_deg, ...
        "Velocity_deg_s", mappedDestinationVelocity_deg_s, ...
        "Acceleration_deg_s2", mappedDestinationAcceleration_deg_s2), ...
    "maximumDiscretizationError", struct( ...
        "Position_deg", options.positionStep_deg / 2, ...
        "Velocity_deg_s", options.velocityStep_deg_s / 2, ...
        "Acceleration_deg_s2", options.accelerationStep_deg_s2 / 2), ...
    "gridRefinement", struct( ...
        "Used", false, ...
        "Schedule_deg", options.positionStep_deg(1), ...
        "Levels", struct.empty(0, 1), ...
        "SelectedLevelIndex", 1, ...
        "SelectedPositionStep_deg", options.positionStep_deg(1), ...
        "FinestLevelSucceeded", success, ...
        "TotalExpandedStateCount", expandedStateCount, ...
        "TotalGeneratedStateCount", generatedStateCount), ...
    "timeRefinement", struct( ...
        "Used", false, ...
        "Schedule_s", options.timeStep_s, ...
        "Levels", struct.empty(0, 1), ...
        "SelectedLevelIndex", 1, ...
        "SelectedTimeStep_s", options.timeStep_s, ...
        "FinestLevelSucceeded", success, ...
        "TotalExpandedStateCount", expandedStateCount, ...
        "TotalGeneratedStateCount", generatedStateCount), ...

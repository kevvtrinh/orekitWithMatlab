function testAnimationFrameBudgetPrefersActualMotion(testCase)
% A long final hold should not consume most of a small animation budget.
% The first half of this plan moves and the second half waits.
time_s = (0:100).';
emptyBoundary = repmat({zeros(0, 1)}, numel(time_s), 1);
data = makeAzElObstacleData( ...
    "Empty", time_s, emptyBoundary, emptyBoundary);
movingPosition_deg = linspace(0, 10, 50).';
position_deg = [ ...
    movingPosition_deg, zeros(50, 1); ...
    repmat([10 0], 51, 1)];
plan = struct( ...
    "success", true, ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "isWaiting", [false(50, 1); true(51, 1)], ...
    "obstacleField", buildAzElTimeObstacleField(data), ...
    "limits", struct( ...
        "azimuth_deg", [-1 11], ...
        "elevation_deg", [-1 1]));

handles = animateAzElAvoidancePlan(data, plan, struct( ...
    "FigureVisible", "off", ...
    "MaximumAnimationFrames", 10, ...
    "PauseSeconds", 0));

verifyLessThanOrEqual(testCase, numel(handles.FrameIndices), 10);
verifyEqual(testCase, handles.FrameIndices([1 end]), [1; 101]);
verifyGreaterThanOrEqual(testCase, ...
    nnz(handles.FrameIndices <= 50), 8);
end


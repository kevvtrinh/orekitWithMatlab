function testApiObstacleExampleCompletesBlockedChordDetour(testCase)
% This rectangle crosses the straight start-to-goal chord used by example
% 01. The example must therefore finish a real Dijkstra detour rather than
% pass only because its direct-path shortcut happened to be available.
time_s = (2700:5:3000).';
azElData = makeAzElObstacleData( ...
    "API regression blocker", time_s, ...
    [10; 30; 30; 10; 10], [20; 20; 50; 50; 20]);
viewOptions = struct( ...
    "FigureVisible", "off", ...
    "PauseSeconds", 0, ...
    "MaximumAnimationFrames", 2, ...
    "MaximumDisplayedSlices", 2);

plan = example01PlanFromAzElData(azElData, viewOptions);

verifyTrue(testCase, plan.success);
verifyEqual(testCase, plan.method, "adaptiveGoalRootedDijkstra");
verifyEqual(testCase, plan.selectedGridStep_deg, 1);
verifyLessThan(testCase, plan.searchElapsed_s, ...
    plan.options.MaxSearchTime_s);
blockedCommandSamples = queryAzElTimeObstacle(plan.obstacleField, ...
    plan.position_deg(:, 1), plan.position_deg(:, 2), plan.time_s, ...
    struct( ...
    "SafetyMarginDeg", plan.options.SafetyMargin_deg, ...
    "TimePaddingSamples", plan.options.TimePaddingSamples));
verifyFalse(testCase, any(blockedCommandSamples));
end


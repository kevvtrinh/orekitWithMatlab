for k = 1:numel(examples)
    source = string(fileread( ...
        fullfile(examples(k).folder, examples(k).name)));
    usesPlanner = contains(source, "planAzElAdaptiveAStar");
    usesRunner = contains(source, "runAzElGauntletCase");

function testAnimatorShowsLatticeContenderAndSelectedRoute(testCase)
time_s = (0:2).';
empty = repmat({zeros(0, 1)}, numel(time_s), 1);
data = makeAzElObstacleData("Empty", time_s, empty, empty);
attemptTemplate = struct( ...
    "GridStep_deg", 2, ...
    "PrimitiveRadii_deg", [2 4], ...
    "Success", true, ...
    "Message", "valid", ...
    "ExpandedNodeCount", 1, ...
    "GeneratedNodeCount", 2, ...
    "SearchElapsed_s", 0.1, ...
    "TerminationReason", "goalReached", ...
    "ObjectiveCost", 3, ...
    "CandidateTime_s", time_s, ...
    "CandidatePosition_deg", [-1 0; 0 0.5; 1 0], ...
    "Selected", false);
selectedAttempt = attemptTemplate;
selectedAttempt.GridStep_deg = 1;
selectedAttempt.ObjectiveCost = 2;
selectedAttempt.CandidatePosition_deg = [-1 0; 0 0; 1 0];
selectedAttempt.Selected = true;
plan = struct( ...
    "success", true, ...
    "time_s", time_s, ...
    "position_deg", selectedAttempt.CandidatePosition_deg, ...
    "workspace", buildAzElTimeObstacleWorkspace(data), ...
    "limits", struct( ...
        "azimuth_deg", [-2 2], ...
        "elevation_deg", [-1 1]), ...
    "selectedGridStep_deg", 1, ...
    "resolutionAttempts", [attemptTemplate; selectedAttempt], ...
    "safeIntervalSearch", struct("EventTimes_s", time_s));

handles = animateAzElAvoidancePlan(data, plan, struct( ...
    "FigureVisible", "off", ...
    "MaximumAnimationFrames", 1, ...
    "PauseSeconds", 0));

verifyTrue(testCase, ...
    isgraphics(handles.TwoDimensional.Discretization, "line"));
verifyEqual(testCase, ...
    numel(handles.TwoDimensional.CandidateRoutes), 1);
verifyTrue(testCase, ...
    isgraphics(handles.TwoDimensional.SelectedRoute, "line"));
verifyTrue(testCase, ...
    isgraphics(handles.ThreeDimensional.Discretization, "line"));
verifyEqual(testCase, ...
    numel(handles.ThreeDimensional.CandidateRoutes), 1);
verifyTrue(testCase, ...
    isgraphics(handles.ThreeDimensional.SelectedRoute, "line"));
end

function testGauntletsDoNotInjectRoutes(testCase)
root = fileparts(fileparts(mfilename("fullpath")));
folder = fullfile(root, "examples");
supportFolder = fullfile(folder, "support");
files = [ ...
    dir(fullfile(folder, "example*.m")); ...
    dir(fullfile(supportFolder, "make*Gauntlet.m"))];
[~, uniqueIndex] = unique({files.name}, "stable");
files = files(uniqueIndex);
for k = 1:numel(files)
    source = string(fileread(fullfile(files(k).folder, files(k).name)));
    verifyEmpty(testCase, regexp(source, ...
        """GuidePath_deg""\s*,|""StateCorridor""\s*,|" + ...
        """ReferencePath[^""]*""\s*,|@planAzElGuidedRoute", ...
        "match"), sprintf('%s injects a route or search corridor.', ...
        files(k).name));
    direction = regexp(source, ...
        '"DirectionAngles_deg"\s*,\s*([^,\r\n]+)', ...
        "tokens");
    for directionIndex = 1:numel(direction)
        value = erase(string(direction{directionIndex}{1}), " ");
        verifyEqual(testCase, value, "0:45:315", ...
            sprintf('%s uses an asymmetric direction hint.', ...
            files(k).name));
    end
end
end

function testStopGoMovesImmediatelyAfterFinalGate(testCase)
set(0, "DefaultFigureVisible", "off");
result = example06StopGoGates();

verifyEqual(testCase, result.blockedSampleCount, 0);
verifyEqual(testCase, result.plan.angularPathLength_deg, 24, ...
    "AbsTol", 1e-9);
verifyLessThanOrEqual(testCase, ...
    result.diagnostics.firstSettledGoalTime_s, 37.5);
afterClearBeforeGoal = result.plan.time_s > 36 & ...
    result.plan.time_s < result.diagnostics.firstSettledGoalTime_s;
verifyFalse(testCase, any( ...
    result.plan.isWaiting(afterClearBeforeGoal)));
end


function testBundledAgentHasAuditableContract(testCase)
packageRoot = fileparts(fileparts(mfilename("fullpath")));
artifactFile = fullfile(packageRoot, ...
    "models", "azElPlannerAgent.mat");
verifyTrue(testCase, isfile(artifactFile));
savedData = load(artifactFile, "agentArtifact");
agentArtifact = savedData.agentArtifact;

verifyEqual(testCase, ...
    agentArtifact.Format, "AzElPlannerSelectionAgent");
verifyEqual(testCase, agentArtifact.Version, 3);
verifyTrue(testCase, agentArtifact.ExactValidationRequired);
verifyEqual(testCase, numel(agentArtifact.Profiles), 10);
verifyEqual(testCase, ...
    string({agentArtifact.Profiles.Name}), ...
    ["fast" "balanced" "precise" "topologyFine" ...
    "dynamicSparseSweep" "dynamicLocalMotion" ...
    "dynamicTiming" "dynamicPursuit" "dynamicDense" ...
    "dynamicLongHorizon"]);
verifyEqual(testCase, ...
    string({agentArtifact.Profiles.Mode}), ...
    ["static" "static" "static" "static" ...
    "dynamic" "dynamic" "dynamic" "dynamic" "dynamic" "dynamic"]);
verifyGreaterThanOrEqual(testCase, ...
    agentArtifact.TrainingReport.TrainingAccuracy, 0.8);
verifyEqual(testCase, ...
    agentArtifact.TrainingReport.ScenarioCount, 36);
verifyEqual(testCase, ...
    agentArtifact.TrainingReport.ValidationScenarioCount, 18);
verifyGreaterThanOrEqual(testCase, ...
    agentArtifact.TrainingReport.ValidationAccuracy, 0.9);
verifyEqual(testCase, ...
    agentArtifact.TrainingReport.NearBestPathRatio, 1.05);
verifyEqual(testCase, ...
    unique(agentArtifact.TrainingReport.SelectedProfileNames), ...
    ["balanced"; "fast"; "precise"]);
end

function testDeploymentReturnsOnlyExactValidatedRoute(testCase)
[azElData, initialState, goalState, axisLimits] = narrowPassageProblem();
plan = planAzElWithAgent( ...
    azElData, initialState, goalState, axisLimits, struct( ...
        "AgentPrintDiagnostics", false, ...
        "AgentMaxSearchTime_s", 20));

verifyTrue(testCase, plan.success);
verifyTrue(testCase, plan.exactCollisionValidated);
verifyNotEmpty(testCase, plan.agent.Attempts);
verifyEqual(testCase, ...
    plan.agent.SelectedProfileName, ...
    plan.agent.Attempts(end).ProfileName);
verifyTrue(testCase, ...
    plan.agent.Attempts(end).ExactCollisionValidated);
verifyEqual(testCase, plan.agent.ProblemMode, "static");
occupied = queryAzElTimeObstacle( ...
    plan.workspace, plan.position_deg(:, 1), ...
    plan.position_deg(:, 2), plan.time_s);
verifyFalse(testCase, any(occupied));
end


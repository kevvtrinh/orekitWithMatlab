function testMovingWorkspaceUsesDynamicPolicy(testCase)
time_s = (0:0.5:12).';
centerAzimuth_deg = -2 + 4 * time_s / time_s(end);
azimuthByTime = cell(numel(time_s), 1);
elevationByTime = cell(numel(time_s), 1);
for sampleIndex = 1:numel(time_s)
    center = centerAzimuth_deg(sampleIndex);
    azimuthByTime{sampleIndex} = [ ...
        center - 0.5; center + 0.5; center + 0.5; ...
        center - 0.5; center - 0.5];
    elevationByTime{sampleIndex} = [-3; -3; -2; -2; -3];
end
azElData = makeAzElObstacleData( ...
    "Moving policy test", time_s, ...
    azimuthByTime, elevationByTime);
initialState = struct( ...
    "time_s", 0, ...
    "position_deg", [-5 2], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", 12, ...
    "position_deg", [5 2], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
axisLimits = struct( ...
    "azimuth_deg", [-6 6], ...
    "elevation_deg", [-4 4], ...
    "maxVelocity_deg_s", [3 3], ...
    "maxAcceleration_deg_s2", [3 3]);
plan = planAzElWithAgent( ...
    azElData, initialState, goalState, axisLimits, struct( ...
        "AgentFallback", false, ...
        "AgentMaxSearchTime_s", 10, ...
        "AgentPrintDiagnostics", false));

verifyEqual(testCase, plan.agent.ProblemMode, "dynamic");
verifyEqual(testCase, ...
    plan.agent.SelectionSource, "dynamicModePolicy");
verifyEqual(testCase, ...
    plan.agent.RankedProfileNames(1), "dynamicSparseSweep");
verifyEqual(testCase, ...
    plan.agent.FeatureDiagnostics.DynamicObstacleCount, 1);
end


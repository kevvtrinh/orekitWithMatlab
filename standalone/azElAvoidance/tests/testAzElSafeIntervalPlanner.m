function testWaitingAppearsForTimedGate(testCase)
problem = makeStopGoGatesGauntlet();
problem.options.PrintFailureSuggestions = false;
plan = planAzElSafeIntervalAStar(problem.azElData, problem.startState, ...
    problem.stopState, problem.limits, problem.options);
verifyTrue(testCase, plan.success);
verifyGreaterThanOrEqual(testCase, ...
    nnz(diff([false; plan.isWaiting; false]) == 1), 3);
verifyPlanIsFree(testCase, plan, problem.options.SafetyMargin_deg);
end

function testImpossibleDeadlineReturnsAssessment(testCase)
[azElData, initialState, ~, limits, options] = standardProblem();
plan = planAzElSafeIntervalAStar(azElData, initialState, ...
    boundaryState(0.5, [4 0]), limits, options);
verifyFalse(testCase, plan.success);
verifyTrue(testCase, isfield(plan, "failureAssessment"));
verifyEqual(testCase, plan.failureAssessment.reasonCode, ...
    "kinematicallyUnreachable");
end


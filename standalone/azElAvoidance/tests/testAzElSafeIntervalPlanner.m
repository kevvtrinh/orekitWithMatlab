    "EarliestInterceptTime_s", 10, ...
    "LatestInterceptTime_s", 14, ...
    "InterceptTimeStep_s", 2, ...
    "MaximumInterceptAttempts", 3, ...
    "PerAttemptMaxSearchTime_s", 8, ...
    "CatchTolerance_deg", 0.05, ...
    "GridStep_deg", 1, ...
    "SampleTime_s", 0.2, ...
    "ValidationStep_s", 0.05, ...
    "SafetyMargin_deg", 0.1, ...
    "MaxSearchTime_s", 8, ...
    "PrintFailureSuggestions", false, ...
    "PlannerFcn", @planAzElSafeIntervalAStar);

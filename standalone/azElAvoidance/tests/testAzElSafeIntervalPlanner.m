function [azElData, initialState, goalState, limits, options] = ...
        standardProblem()
time_s = (0:10).';
azElData = makeAzElObstacleData("Empty", time_s, zeros(0, 1), zeros(0, 1));
initialState = boundaryState(0, [-4 0]);
goalState = boundaryState(10, [4 0]);
limits = struct( ...
    "azimuth_deg", [-10 10], ...
    "elevation_deg", [-5 5], ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [1 1]);
options = struct( ...
    "GridStep_deg", 1, ...
    "SampleTime_s", 0.5, ...
    "MaxSearchTime_s", 8, ...
    "PrintFailureSuggestions", false);
end

function state = boundaryState(time_s, position_deg)
state = struct( ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
end

function verifyPlanIsFree(testCase, plan, safetyMargin_deg)
blocked = queryAzElTimeObstacle(plan.workspace, ...
    plan.position_deg(:, 1), plan.position_deg(:, 2), plan.time_s, ...
    struct("SafetyMarginDeg", safetyMargin_deg, "TimePaddingSamples", 1));
verifyEqual(testCase, nnz(blocked), 0);
verifyLessThanOrEqual(testCase, max(abs(plan.velocity_deg_s), [], 1), ...
    plan.limits.maxVelocity_deg_s + 1e-8);
verifyLessThanOrEqual(testCase, ...
    max(abs(plan.acceleration_deg_s2), [], 1), ...
    plan.limits.maxAcceleration_deg_s2 + 1e-8);
end

function testEmptyFieldStraightLineIsOptimal(testCase)
[azElData, initialState, goalState, limits, options] = standardProblem();
plan = planAzElSafeIntervalAStar( ...
    azElData, initialState, goalState, limits, options);
verifyTrue(testCase, plan.success);
verifyEqual(testCase, plan.method, "safeIntervalAStar");
verifyEqual(testCase, plan.angularPathLength_deg, 8, "AbsTol", 1e-9);
verifyTrue(testCase, plan.optimalGlobally);
verifyEqual(testCase, plan.position_deg(end, :), ...
    goalState.position_deg, "AbsTol", 1e-9);
verifyPlanIsFree(testCase, plan, 0);
end


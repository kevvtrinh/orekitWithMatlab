function testMovingWallForcesTimedCrossing(testCase)
time_s = (0:0.5:30).';
sampleCount = numel(time_s);
azimuth = cell(sampleCount, 1);
elevation = cell(sampleCount, 1);
% A full-height wall blocks azimuth zero except for a short opening that
% sweeps upward in elevation, so the crossing must be timed, not routed.
for k = 1:sampleCount
    gapCenter = -4 + 0.4 * time_s(k);
    azimuth{k} = [-0.5; 0.5; 0.5; -0.5; -0.5; NaN; ...
        -0.5; 0.5; 0.5; -0.5; -0.5];
    elevation{k} = [-6; -6; gapCenter - 1; gapCenter - 1; -6; NaN; ...
        gapCenter + 1; gapCenter + 1; 6; 6; gapCenter + 1];
end
azElData = struct( ...
    "targetName", "Sweeping gap wall", ...
    "time_s", time_s, ...
    "az_deg", {azimuth}, ...
    "el_deg", {elevation}, ...
    "status", "visible");
limits = struct( ...
    "azimuth_deg", [-8 8], ...
    "elevation_deg", [-6 6], ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [2 2]);
options = struct( ...
    "GridStep_deg", 1, ...
    "SampleTime_s", 0.25, ...
    "SafetyMargin_deg", 0.1, ...
    "MaxSearchTime_s", 30, ...
    "PrintFailureSuggestions", false);
plan = planAzElSafeIntervalAStar(azElData, boundaryState(0, [-5 0]), ...
    boundaryState(30, [5 0]), limits, options);
verifyTrue(testCase, plan.success);
verifyPlanIsFree(testCase, plan, options.SafetyMargin_deg);
end


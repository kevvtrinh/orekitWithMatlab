function testSummaryBuildsDijkstraLatticeAndFinalSelection(testCase)
[azElData, plan] = dijkstraFixture();
handles = animateAzElAvoidancePlan(azElData, plan, struct( ...
    "FigureVisible", "off", ...
    "MaximumAnimationFrames", 3, ...
    "PauseSeconds", 0, ...
    "ShowPlanningSummary", true));

verifyEqual(testCase, handles.Options.DiscretizationMode, "build");
verifyTrue(testCase, isgraphics(handles.SummaryTitle));
verifyEqual(testCase, handles.PlanningSummary.SearchType, ...
    "Dijkstra lattice");
verifyEqual(testCase, handles.PlanningSummary.ValidContenderCount, 1);
verifyEqual(testCase, handles.PlanningSummary.PackedSliceCount, 3);
verifyNotEmpty(testCase, handles.TwoDimensional.Discretization);
layerStatus = get( ...
    handles.TwoDimensional.Discretization(1), "UserData");
verifyTrue(testCase, layerStatus.Complete);
verifyGreaterThan(testCase, layerStatus.TotalItemCount, 0);
verifyEqual(testCase, ...
    string(get(handles.TwoDimensional.SelectedRoute, "Visible")), "on");
verifyTrue(testCase, contains(string(handles.SummaryTitle.String), ...
    "Selected:"));
end


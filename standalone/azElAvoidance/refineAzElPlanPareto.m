function [position_deg, velocity_deg_s, acceleration_deg_s2] = ...
        endpointQuinticMotion(time_s, duration_s, initialState, goalState)
% A fifth-order polynomial is the lowest order that can match position,
% velocity, and acceleration at both endpoints. Normalized time keeps the
% small coefficient solve well conditioned for both short and long missions.
initialPosition_deg = initialState.position_deg;
initialVelocityScaled_deg = initialState.velocity_deg_s * duration_s;
initialAccelerationScaled_deg = ...
    initialState.acceleration_deg_s2 * duration_s^2;
goalVelocityScaled_deg = goalState.velocity_deg_s * duration_s;
goalAccelerationScaled_deg = ...
    goalState.acceleration_deg_s2 * duration_s^2;
coefficient0 = initialPosition_deg;
coefficient1 = initialVelocityScaled_deg;
coefficient2 = 0.5 * initialAccelerationScaled_deg;
remainingPosition_deg = goalState.position_deg - ...
    coefficient0 - coefficient1 - coefficient2;
remainingVelocity_deg = goalVelocityScaled_deg - ...
    coefficient1 - 2 * coefficient2;
remainingAcceleration_deg = goalAccelerationScaled_deg - ...
    2 * coefficient2;
coefficientMatrix = [1 1 1; 3 4 5; 6 12 20];
higherCoefficients = coefficientMatrix \ [ ...
    remainingPosition_deg; remainingVelocity_deg; ...
    remainingAcceleration_deg];
coefficient3 = higherCoefficients(1, :);
coefficient4 = higherCoefficients(2, :);
coefficient5 = higherCoefficients(3, :);
normalizedTime = time_s / duration_s;
position_deg = coefficient0 + normalizedTime .* coefficient1 + ...
    normalizedTime.^2 .* coefficient2 + ...
    normalizedTime.^3 .* coefficient3 + ...
    normalizedTime.^4 .* coefficient4 + ...
    normalizedTime.^5 .* coefficient5;
velocity_deg_s = (coefficient1 + ...
    2 * normalizedTime .* coefficient2 + ...
    3 * normalizedTime.^2 .* coefficient3 + ...
    4 * normalizedTime.^3 .* coefficient4 + ...
    5 * normalizedTime.^4 .* coefficient5) / duration_s;
acceleration_deg_s2 = (2 * coefficient2 + ...
    6 * normalizedTime .* coefficient3 + ...
    12 * normalizedTime.^2 .* coefficient4 + ...
    20 * normalizedTime.^3 .* coefficient5) / duration_s^2;
end

function sample = sampleQuinticNodeStates( ...
        nodeTime_s, nodePosition_deg, nodeVelocity_deg_s, ...
        nodeAcceleration_deg_s2, maximumSampleStep_s)
% Each neighboring state pair owns one quintic segment. Matching both
% endpoint accelerations prevents artificial velocity or acceleration jumps
% at the original planner samples.
segmentCount = numel(nodeTime_s) - 1;
sampleCapacity = max(2, ceil((nodeTime_s(end) - nodeTime_s(1)) / ...
    maximumSampleStep_s) + segmentCount + 1);
time_s = zeros(sampleCapacity, 1);
position_deg = zeros(sampleCapacity, 2);
velocity_deg_s = zeros(sampleCapacity, 2);
acceleration_deg_s2 = zeros(sampleCapacity, 2);
jerk_deg_s3 = zeros(sampleCapacity, 2);
sampleCount = 1;
time_s(1) = nodeTime_s(1);
position_deg(1, :) = nodePosition_deg(1, :);
velocity_deg_s(1, :) = nodeVelocity_deg_s(1, :);
acceleration_deg_s2(1, :) = nodeAcceleration_deg_s2(1, :);

for segmentIndex = 1:segmentCount
    duration_s = nodeTime_s(segmentIndex + 1) - ...
        nodeTime_s(segmentIndex);
    if duration_s <= 0
        continue
    end
    intervalCount = max(1, ceil(duration_s / maximumSampleStep_s));
    normalizedTime = (1:intervalCount).' / intervalCount;
    segmentSampleCount = numel(normalizedTime);
    requiredCapacity = sampleCount + segmentSampleCount;
    if requiredCapacity > sampleCapacity
        newCapacity = max(requiredCapacity, 2 * sampleCapacity);
        time_s(newCapacity, 1) = 0;
        position_deg(newCapacity, 2) = 0;
        velocity_deg_s(newCapacity, 2) = 0;
        acceleration_deg_s2(newCapacity, 2) = 0;
        jerk_deg_s3(newCapacity, 2) = 0;
        sampleCapacity = newCapacity;
    end
    positionDelta_deg = nodePosition_deg(segmentIndex + 1, :) - ...
        nodePosition_deg(segmentIndex, :);
    scaledInitialVelocity_deg = ...
        duration_s * nodeVelocity_deg_s(segmentIndex, :);
    scaledFinalVelocity_deg = ...
        duration_s * nodeVelocity_deg_s(segmentIndex + 1, :);
    scaledInitialAcceleration_deg = ...
        duration_s^2 * nodeAcceleration_deg_s2(segmentIndex, :);
    scaledFinalAcceleration_deg = ...
        duration_s^2 * nodeAcceleration_deg_s2(segmentIndex + 1, :);
    coefficient0 = nodePosition_deg(segmentIndex, :);
    coefficient1 = scaledInitialVelocity_deg;
    coefficient2 = 0.5 * scaledInitialAcceleration_deg;
    coefficient3 = 10 * positionDelta_deg - ...
        6 * scaledInitialVelocity_deg - 4 * scaledFinalVelocity_deg - ...
        1.5 * scaledInitialAcceleration_deg + ...
        0.5 * scaledFinalAcceleration_deg;
    coefficient4 = -15 * positionDelta_deg + ...
        8 * scaledInitialVelocity_deg + 7 * scaledFinalVelocity_deg + ...
        1.5 * scaledInitialAcceleration_deg - ...
        scaledFinalAcceleration_deg;
    coefficient5 = 6 * positionDelta_deg - ...
        3 * scaledInitialVelocity_deg - 3 * scaledFinalVelocity_deg - ...
        0.5 * scaledInitialAcceleration_deg + ...
        0.5 * scaledFinalAcceleration_deg;
    if segmentIndex == 1
        % The first sample is not generated by the loop below. Record its
        % exact right-hand jerk so the dense limit check includes launch.
        jerk_deg_s3(1, :) = 6 * coefficient3 / duration_s^3;
    end
    sampleRows = sampleCount + (1:segmentSampleCount);
    time_s(sampleRows) = nodeTime_s(segmentIndex) + ...
        duration_s * normalizedTime;
    position_deg(sampleRows, :) = coefficient0 + ...
        normalizedTime .* coefficient1 + ...
        normalizedTime.^2 .* coefficient2 + ...
        normalizedTime.^3 .* coefficient3 + ...
        normalizedTime.^4 .* coefficient4 + ...
        normalizedTime.^5 .* coefficient5;
    velocity_deg_s(sampleRows, :) = (coefficient1 + ...
        2 * normalizedTime .* coefficient2 + ...
        3 * normalizedTime.^2 .* coefficient3 + ...
        4 * normalizedTime.^3 .* coefficient4 + ...
        5 * normalizedTime.^4 .* coefficient5) / duration_s;
    acceleration_deg_s2(sampleRows, :) = (2 * coefficient2 + ...
        6 * normalizedTime .* coefficient3 + ...
        12 * normalizedTime.^2 .* coefficient4 + ...
        20 * normalizedTime.^3 .* coefficient5) / duration_s^2;
    jerk_deg_s3(sampleRows, :) = (6 * coefficient3 + ...
        24 * normalizedTime .* coefficient4 + ...
        60 * normalizedTime.^2 .* coefficient5) / duration_s^3;
    sampleCount = requiredCapacity;
end

sample = struct( ...
    "Time_s", time_s(1:sampleCount), ...
    "PositionUnwrapped_deg", position_deg(1:sampleCount, :), ...
    "Position_deg", position_deg(1:sampleCount, :), ...
    "Velocity_deg_s", velocity_deg_s(1:sampleCount, :), ...
    "Acceleration_deg_s2", acceleration_deg_s2(1:sampleCount, :), ...
    "Jerk_deg_s3", jerk_deg_s3(1:sampleCount, :), ...
    "IsWaiting", false(sampleCount, 1));
end

function requiredScale = requiredPhysicalTimeScale( ...
        sample, limits, maximumJerk_deg_s3)
velocityRatio = max(abs(sample.Velocity_deg_s) ./ ...
    limits.maxVelocity_deg_s, [], "all");
accelerationRatio = max(abs(sample.Acceleration_deg_s2) ./ ...
    limits.maxAcceleration_deg_s2, [], "all");
jerkRatio = max(abs(sample.Jerk_deg_s3) ./ ...
    maximumJerk_deg_s3, [], "all");
requiredScale = max([velocityRatio, sqrt(accelerationRatio), ...
    nthroot(max(jerkRatio, 0), 3), 0]);
requiredScale = requiredScale * 1.0001;
end

function [candidateIsSafe, sample] = verifyParetoCandidate( ...
        sample, obstacleField, initialState, goalState, limits, options)
% Append the terminal hold before validation. Dynamic examples can therefore
% reject an earlier arrival when the goal later becomes occupied.
completionTime_s = sample.Time_s(end) + initialState.time_s;
sample.Time_s = sample.Time_s + initialState.time_s;
hasTerminalDynamics = any(abs([goalState.velocity_deg_s, ...
    goalState.acceleration_deg_s2]) > 1e-12);
if hasTerminalDynamics && abs(completionTime_s - goalState.time_s) > 1e-8
    candidateIsSafe = false;
    return
end
if completionTime_s < goalState.time_s - 1e-12
    waitingTime_s = (completionTime_s + options.ValidationStep_s: ...
        options.ValidationStep_s:goalState.time_s).';
    if isempty(waitingTime_s) || waitingTime_s(end) < goalState.time_s
        waitingTime_s(end + 1, 1) = goalState.time_s;
    end
    waitingCount = numel(waitingTime_s);
    sample.Time_s = [sample.Time_s; waitingTime_s];
    sample.PositionUnwrapped_deg = [sample.PositionUnwrapped_deg; ...
        repmat(sample.PositionUnwrapped_deg(end, :), waitingCount, 1)];
    sample.Velocity_deg_s = [sample.Velocity_deg_s; ...
        zeros(waitingCount, 2)];
    sample.Acceleration_deg_s2 = [sample.Acceleration_deg_s2; ...
        zeros(waitingCount, 2)];
    sample.Jerk_deg_s3 = [sample.Jerk_deg_s3; zeros(waitingCount, 2)];
    sample.IsWaiting = [sample.IsWaiting; true(waitingCount, 1)];
end

sample.Position_deg = sample.PositionUnwrapped_deg;
if options.AllowAzimuthWrap
    azimuthMinimum_deg = limits.azimuth_deg(1);
    azimuthSpan_deg = diff(limits.azimuth_deg);
    sample.Position_deg(:, 1) = azimuthMinimum_deg + mod( ...
        sample.Position_deg(:, 1) - azimuthMinimum_deg, azimuthSpan_deg);
end
insideElevation = sample.PositionUnwrapped_deg(:, 2) >= ...
    limits.elevation_deg(1) - 1e-8 & ...
    sample.PositionUnwrapped_deg(:, 2) <= limits.elevation_deg(2) + 1e-8;
insideAzimuth = true(size(insideElevation));
if ~options.AllowAzimuthWrap
    insideAzimuth = sample.PositionUnwrapped_deg(:, 1) >= ...
        limits.azimuth_deg(1) - 1e-8 & ...
        sample.PositionUnwrapped_deg(:, 1) <= ...
        limits.azimuth_deg(2) + 1e-8;
end
derivativesAreSafe = all(abs(sample.Velocity_deg_s) <= ...
    limits.maxVelocity_deg_s + 1e-8, "all") && ...
    all(abs(sample.Acceleration_deg_s2) <= ...
    limits.maxAcceleration_deg_s2 + 1e-8, "all") && ...
    all(abs(sample.Jerk_deg_s3) <= ...
    options.JointKinematicMaximumJerk_deg_s3 + 1e-8, "all");
if ~all(insideAzimuth & insideElevation) || ~derivativesAreSafe
    candidateIsSafe = false;
    return
end
blocked = queryAzElTimeObstacle(obstacleField, ...
    sample.Position_deg(:, 1), sample.Position_deg(:, 2), ...
    sample.Time_s, struct( ...
    "SafetyMarginDeg", options.SafetyMargin_deg, ...
    "TimePaddingSamples", options.TimePaddingSamples));
candidateIsSafe = ~any(blocked);
end

function ratio = combinedParetoRatio(duration_s, pathLength_deg, ...
        timeLowerBound_s, distanceLowerBound_deg, options)
ratio = options.JointKinematicTimeWeight * ...
    duration_s / timeLowerBound_s + ...
    options.JointKinematicDistanceWeight * ...
    pathLength_deg / distanceLowerBound_deg;
end

function lowerBound_s = restToRestTimeLowerBound( ...
        startPosition_deg, goalPosition_deg, limits)
distanceByAxis_deg = abs(goalPosition_deg - startPosition_deg);
axisTime_s = zeros(1, 2);
for axisIndex = 1:2
    maximumVelocity_deg_s = limits.maxVelocity_deg_s(axisIndex);
    maximumAcceleration_deg_s2 = ...
        limits.maxAcceleration_deg_s2(axisIndex);
    accelerationDistance_deg = maximumVelocity_deg_s^2 / ...
        maximumAcceleration_deg_s2;
    if distanceByAxis_deg(axisIndex) <= accelerationDistance_deg
        axisTime_s(axisIndex) = 2 * sqrt( ...
            distanceByAxis_deg(axisIndex) / maximumAcceleration_deg_s2);
    else
        axisTime_s(axisIndex) = distanceByAxis_deg(axisIndex) / ...
            maximumVelocity_deg_s + maximumVelocity_deg_s / ...
            maximumAcceleration_deg_s2;
    end
end
lowerBound_s = max(axisTime_s);
end

function value = fieldOr(record, fieldName, fallback)
if isstruct(record) && isfield(record, fieldName) && ...
        ~isempty(record.(fieldName)) && isfinite(record.(fieldName))
    value = record.(fieldName);
else
    value = fallback;
end

    max(maximumPosition_deg(:, 1)) <= ...
    azimuthLimits_deg(2) + tolerance_deg && ...
    min(minimumPosition_deg(:, 2)) >= ...
    elevationLimits_deg(1) - tolerance_deg && ...
    max(maximumPosition_deg(:, 2)) <= ...
    elevationLimits_deg(2) + tolerance_deg;
end


    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
for fieldName = string(fieldnames(stateDefaults)).'
    if ~isfield(initialState, fieldName)
        initialState.(fieldName) = stateDefaults.(fieldName);
    end
    if ~isfield(goalState, fieldName)
        goalState.(fieldName) = stateDefaults.(fieldName);
    end
end
requiredStateFields = ["time_s", "position_deg", ...
    "velocity_deg_s", "acceleration_deg_s2"];
for fieldName = requiredStateFields
    validateattributes(initialState.(fieldName), {'numeric'}, ...
        {'real', 'finite'});
    validateattributes(goalState.(fieldName), {'numeric'}, ...
        {'real', 'finite'});
end

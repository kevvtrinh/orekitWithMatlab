    double(goalState.velocity_deg_s), 1, 2);
initialState.acceleration_deg_s2 = reshape( ...
    double(initialState.acceleration_deg_s2), 1, 2);
goalState.acceleration_deg_s2 = reshape( ...
    double(goalState.acceleration_deg_s2), 1, 2);
if goalState.time_s <= initialState.time_s
    error("planAzElBidirectionalKinodynamicRRTStar:TimeOrder", ...
        "goalState.time_s must be later than initialState.time_s.");
end

limitFields = ["azimuth_deg", "elevation_deg", ...
    "maxVelocity_deg_s", "maxAcceleration_deg_s2"];
for fieldName = limitFields
    validateattributes(limits.(fieldName), {'numeric'}, ...
        {'vector', 'numel', 2, 'real', 'finite'});
    limits.(fieldName) = reshape(double(limits.(fieldName)), 1, 2);
end


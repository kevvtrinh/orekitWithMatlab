function plan = planAzElMovingTargetIntercept( ...
        azElData, initialState, target, limits, options)
%PLANAZELMOVINGTARGETINTERCEPT Catch a moving point through dynamic volumes.
%
% The target trajectory is independent of the obstacle field. Candidate
% interception times are sampled across the requested interval and attempted
% from earliest to latest. Optional terminal capture matches target velocity
% and acceleration, then follows the target while its path remains safe.

%% Normalize and validate target inputs
if nargin < 5
    options = struct();
end
requiredTarget = ["time_s", "position_deg"];
if ~isstruct(target) || ~isscalar(target) || ...
        ~all(isfield(target, requiredTarget))
    error("planAzElMovingTargetIntercept:InvalidTarget", ...
        "target requires time_s and position_deg.");
end
target.time_s = double(target.time_s(:));
target.position_deg = double(target.position_deg);
validateattributes(target.time_s, {'numeric'}, ...
    {'vector', 'real', 'finite', 'increasing'});
validateattributes(target.position_deg, {'numeric'}, ...
    {'2d', 'ncols', 2, 'real', 'finite'});
if size(target.position_deg, 1) ~= numel(target.time_s)
    error("planAzElMovingTargetIntercept:TargetSizeMismatch", ...
        "target.position_deg must contain one row per target time.");
end

defaultOptions = struct( ...
    "EarliestInterceptTime_s", ...
        max(initialState.time_s, target.time_s(1)), ...
    "LatestInterceptTime_s", target.time_s(end), ...
    "InterceptTimeStep_s", 2, ...
    "MaximumInterceptAttempts", 12, ...
    "PerAttemptMaxSearchTime_s", 8, ...
    "CatchTolerance_deg", 0.35, ...
    "CatchVelocityTolerance_deg_s", 0.05, ...
    "CatchAccelerationTolerance_deg_s2", 0.1, ...
    "MatchTargetVelocity", false, ...
    "MatchTargetAcceleration", false, ...
    "ContinueTrackingAfterIntercept", false, ...
    "TrackingEndTime_s", target.time_s(end), ...
    "TrackingSampleTime_s", fieldOr(options, "SampleTime_s", 0.5), ...
    "SafetyMargin_deg", 0, ...
    "PrintFailureSuggestions", true);
defaultOptionFields = fieldnames(defaultOptions);
for defaultOptionIndex = 1:numel(defaultOptionFields)
    defaultOptionField = defaultOptionFields{defaultOptionIndex};
    if ~isfield(options, defaultOptionField) || ...
            isempty(options.(defaultOptionField))
        options.(defaultOptionField) = defaultOptions.(defaultOptionField);
    end
end
positiveOptionFields = ["InterceptTimeStep_s", ...
    "PerAttemptMaxSearchTime_s", "CatchTolerance_deg", ...
    "CatchVelocityTolerance_deg_s", ...
    "CatchAccelerationTolerance_deg_s2", "TrackingSampleTime_s"];
for positiveOptionField = positiveOptionFields
    validateattributes(options.(positiveOptionField), {'numeric'}, ...
        {'scalar', 'real', 'finite', 'positive'});
end
validateattributes(options.MaximumInterceptAttempts, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(options.EarliestInterceptTime_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', ...
    '>=', max(initialState.time_s, target.time_s(1))});
validateattributes(options.LatestInterceptTime_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', '<=', target.time_s(end)});
if options.LatestInterceptTime_s <= options.EarliestInterceptTime_s
    error("planAzElMovingTargetIntercept:InvalidInterceptWindow", ...
        "LatestInterceptTime_s must follow EarliestInterceptTime_s.");
end
validateattributes(options.TrackingEndTime_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', '<=', target.time_s(end)});
logicalOptionFields = ["MatchTargetVelocity", ...
    "MatchTargetAcceleration", "ContinueTrackingAfterIntercept", ...
    "PrintFailureSuggestions"];
for logicalOptionField = logicalOptionFields
    validateattributes(options.(logicalOptionField), ...
        {'logical', 'numeric'}, {'scalar'});
    % Normalize numeric 0/1 once so later branches and exported options
    % expose a stable logical type.
    options.(logicalOptionField) = logical( ...
        options.(logicalOptionField));
end
if options.MatchTargetAcceleration && ~options.MatchTargetVelocity
    error("planAzElMovingTargetIntercept:AccelerationWithoutVelocity", ...
        "MatchTargetAcceleration requires MatchTargetVelocity.");
end
if options.ContinueTrackingAfterIntercept && ...
        ~options.MatchTargetVelocity
    error("planAzElMovingTargetIntercept:TrackingWithoutVelocityMatch", ...
        "ContinueTrackingAfterIntercept requires MatchTargetVelocity.");
end

%% Derive continuous target kinematics
targetSampleCount = numel(target.time_s);
allowAzimuthWrap = fieldOr(options, "AllowAzimuthWrap", ...
    diff(limits.azimuth_deg) >= 360 - 1e-9);
targetPositionUnwrapped_deg = target.position_deg;
% Differentiate a continuous azimuth trace. Wrapped samples would create
% artificial velocity spikes at the azimuth seam.
if allowAzimuthWrap
    targetPositionUnwrapped_deg(:, 1) = rad2deg( ...
        unwrap(deg2rad(targetPositionUnwrapped_deg(:, 1))));
end
if isfield(target, "velocity_deg_s") && ...
        ~isempty(target.velocity_deg_s)
    targetVelocity_deg_s = normalizeTargetSamples( ...
        target.velocity_deg_s, targetSampleCount, "velocity_deg_s");
else
    targetVelocity_deg_s = sampledDerivative( ...
        targetPositionUnwrapped_deg, target.time_s);
end
if isfield(target, "acceleration_deg_s2") && ...
        ~isempty(target.acceleration_deg_s2)
    targetAcceleration_deg_s2 = normalizeTargetSamples( ...
        target.acceleration_deg_s2, targetSampleCount, ...
        "acceleration_deg_s2");
else
    targetAcceleration_deg_s2 = sampledDerivative( ...
        targetVelocity_deg_s, target.time_s);
end
target.positionUnwrapped_deg = targetPositionUnwrapped_deg;
target.position_deg = canonicalPosition( ...
    targetPositionUnwrapped_deg, limits, options);
target.velocity_deg_s = targetVelocity_deg_s;
target.acceleration_deg_s2 = targetAcceleration_deg_s2;

%% Build the obstacle workspace once for all interception attempts
% Build once because every candidate interception time reuses the same
% moving obstacle volume.
if isstruct(azElData) && isscalar(azElData) && ...
        isfield(azElData, "Format") && ...
        azElData.Format == "AzElTimeObstacleWorkspace"
    workspace = azElData;
else
    maximumVertices = fieldOr(options, ...
        "MaximumVerticesPerRegion", 500);
    workspace = buildAzElTimeObstacleWorkspace(azElData, struct( ...
        "MaximumVerticesPerRegion", maximumVertices));
end

%% Filter sampled interception candidates
candidateTime = (options.EarliestInterceptTime_s: ...
    options.InterceptTimeStep_s:options.LatestInterceptTime_s).';
if isempty(candidateTime) || ...
        candidateTime(end) < options.LatestInterceptTime_s - 1e-9
    candidateTime(end + 1, 1) = options.LatestInterceptTime_s;
end
candidateUnwrapped = interp1( ...
    target.time_s, target.positionUnwrapped_deg, ...
    candidateTime, "linear");
candidatePosition = canonicalPosition( ...
    candidateUnwrapped, limits, options);
candidateVelocity = interp1(target.time_s, target.velocity_deg_s, ...
    candidateTime, "linear");
candidateAcceleration = interp1( ...
    target.time_s, target.acceleration_deg_s2, ...
    candidateTime, "linear");
% Cheap point, collision, and reachability filters avoid launching Dijkstra for
% interception states that cannot possibly succeed.
inside = candidatePosition(:, 1) >= limits.azimuth_deg(1) & ...
    candidatePosition(:, 1) <= limits.azimuth_deg(2) & ...
    candidatePosition(:, 2) >= limits.elevation_deg(1) & ...
    candidatePosition(:, 2) <= limits.elevation_deg(2);
blocked = true(size(candidateTime));
blocked(inside) = queryAzElTimeObstacle(workspace, ...
    candidatePosition(inside, 1), candidatePosition(inside, 2), ...
    candidateTime(inside), struct( ...
    "SafetyMarginDeg", options.SafetyMargin_deg, ...
    "TimePaddingSamples", 1));
candidateDisplacement_deg = abs( ...
    candidatePosition - initialState.position_deg);
if allowAzimuthWrap
    azimuthSpan_deg = diff(limits.azimuth_deg);
    candidateDisplacement_deg(:, 1) = abs(mod( ...
        candidatePosition(:, 1) - initialState.position_deg(1) + ...
        azimuthSpan_deg / 2, azimuthSpan_deg) - azimuthSpan_deg / 2);
end
minimumVelocityTime_s = max(candidateDisplacement_deg ./ ...
    limits.maxVelocity_deg_s, [], 2);
minimumAccelerationTime_s = max(sqrt( ...
    2 * candidateDisplacement_deg ./ ...
    limits.maxAcceleration_deg_s2), [], 2);
minimumReachTime_s = max( ...
    minimumVelocityTime_s, minimumAccelerationTime_s);
availableReachTime_s = candidateTime - initialState.time_s + 1e-9;
reachable = minimumReachTime_s <= availableReachTime_s;
if options.MatchTargetVelocity
    maximumCandidateVelocity_deg_s = limits.maxVelocity_deg_s + 1e-9;
    velocityInsideLimits = abs(candidateVelocity) <= maximumCandidateVelocity_deg_s;
    reachable = reachable & all(velocityInsideLimits, 2);
end
if options.MatchTargetAcceleration
    maximumCandidateAcceleration_deg_s2 = limits.maxAcceleration_deg_s2 + 1e-9;
    accelerationInsideLimits = abs(candidateAcceleration) <= maximumCandidateAcceleration_deg_s2;
    reachable = reachable & all(accelerationInsideLimits, 2);
end
eligible = inside & ~blocked & reachable;
eligibleIndex = find(eligible);
if numel(eligibleIndex) > options.MaximumInterceptAttempts
    selected = unique(round(linspace( ...
        1, numel(eligibleIndex), options.MaximumInterceptAttempts)));
    eligibleIndex = eligibleIndex(selected);
end

attemptTemplate = struct( ...
    "time_s", NaN, ...
    "position_deg", [NaN NaN], ...
    "velocity_deg_s", [NaN NaN], ...
    "success", false, ...
    "elapsed_s", 0, ...
    "message", "");
attempts = repmat(attemptTemplate, numel(eligibleIndex), 1);
attemptCount = 0;
timer = tic;
%% Try eligible rendezvous states from earliest to latest
% Earliest-first attempts make the first accepted plan the earliest sampled
% rendezvous. Every attempt has its own bounded search budget.
for attemptCandidateIndex = 1:numel(eligibleIndex)
    candidateIndex = eligibleIndex(attemptCandidateIndex);
    goalVelocity_deg_s = [0 0];
    goalAcceleration_deg_s2 = [0 0];
    if options.MatchTargetVelocity
        goalVelocity_deg_s = candidateVelocity(candidateIndex, :);
    end
    if options.MatchTargetAcceleration
        goalAcceleration_deg_s2 = candidateAcceleration(candidateIndex, :);
    end
    goalState = struct( ...
        "time_s", candidateTime(candidateIndex), ...
        "position_deg", candidatePosition(candidateIndex, :), ...
        "velocity_deg_s", goalVelocity_deg_s, ...
        "acceleration_deg_s2", goalAcceleration_deg_s2);
    plannerOptions = options;
    plannerOptions.AllowNonzeroTerminalState = options.MatchTargetVelocity || ...
        options.MatchTargetAcceleration;
    plannerOptions.MaxSearchTime_s = min( ...
        options.PerAttemptMaxSearchTime_s, ...
        fieldOr(options, "MaxSearchTime_s", ...
        options.PerAttemptMaxSearchTime_s));
    plannerOptions.PrintFailureSuggestions = false;
    attemptTimer = tic;
    candidate = planAzElDijkstra( ...
        workspace, initialState, goalState, limits, plannerOptions);
    attemptCount = attemptCount + 1;
    attempts(attemptCount, 1) = struct( ...
        "time_s", candidateTime(candidateIndex), ...
        "position_deg", candidatePosition(candidateIndex, :), ...
        "velocity_deg_s", candidateVelocity(candidateIndex, :), ...
        "success", candidate.success, ...
        "elapsed_s", toc(attemptTimer), ...
        "message", string(candidate.message));
    if ~candidate.success
        continue;
    end
    % Re-evaluate target kinematics at the reported catch time. This catches
    % interpolation, wrapping, and profile-sampling inconsistencies.
    targetAtCatchUnwrapped = interp1( ...
        target.time_s, target.positionUnwrapped_deg, ...
        candidate.time_s(end), "linear");
    targetAtCatch = canonicalPosition( ...
        targetAtCatchUnwrapped, limits, options);
    targetVelocityAtCatch = interp1( ...
        target.time_s, target.velocity_deg_s, ...
        candidate.time_s(end), "linear");
    targetAccelerationAtCatch = interp1( ...
        target.time_s, target.acceleration_deg_s2, ...
        candidate.time_s(end), "linear");
    catchError = hypot( ...
        candidate.position_deg(end, 1) - targetAtCatch(1), ...
        candidate.position_deg(end, 2) - targetAtCatch(2));
    if catchError > options.CatchTolerance_deg + 1e-9
        continue;
    end
    velocityError = hypot( ...
        candidate.velocity_deg_s(end, 1) - targetVelocityAtCatch(1), ...
        candidate.velocity_deg_s(end, 2) - targetVelocityAtCatch(2));
    if options.MatchTargetVelocity && ...
            velocityError > ...
            options.CatchVelocityTolerance_deg_s + 1e-9
        continue;
    end
    accelerationError = hypot( ...
        candidate.acceleration_deg_s2(end, 1) - ...
            targetAccelerationAtCatch(1), ...
        candidate.acceleration_deg_s2(end, 2) - ...
            targetAccelerationAtCatch(2));
    if options.MatchTargetAcceleration && ...
            accelerationError > ...
            options.CatchAccelerationTolerance_deg_s2 + 1e-9
        continue;
    end
    plan = candidate;
    plan.interceptSuccess = true;
    plan.interceptTime_s = candidate.time_s(end);
    plan.interceptPosition_deg = candidate.position_deg(end, :);
    plan.targetPositionAtIntercept_deg = targetAtCatch;
    plan.targetVelocityAtIntercept_deg_s = targetVelocityAtCatch;
    plan.targetAccelerationAtIntercept_deg_s2 = targetAccelerationAtCatch;
    plan.catchError_deg = catchError;
    plan.catchVelocityError_deg_s = velocityError;
    plan.catchAccelerationError_deg_s2 = accelerationError;
    plan.targetTrajectory = target;
    plan.interceptAttempts = attempts(1:attemptCount);
    plan.interceptCandidateCount = nnz(eligible);
    plan.interceptSearchElapsed_s = toc(timer);

    %% Follow the target until the first unsafe tracking sample
    plan.trackingRequested = options.ContinueTrackingAfterIntercept;
    plan.trackingSuccess = false;
    plan.trackingTerminationReason = "notRequested";
    plan.trackingTerminatedByObstacle = false;
    plan.trackingTime_s = zeros(0, 1);
    plan.trackingPosition_deg = zeros(0, 2);
    plan.trackingVelocity_deg_s = zeros(0, 2);
    plan.trackingAcceleration_deg_s2 = zeros(0, 2);
    plan.trackingEndTime_s = plan.interceptTime_s;
    if options.ContinueTrackingAfterIntercept
        trackingStopTime_s = min( ...
            options.TrackingEndTime_s, target.time_s(end));
        if trackingStopTime_s <= plan.interceptTime_s + 1e-9
            plan.trackingTerminationReason = "trackingWindowComplete";
        else
            trackingDuration_s = trackingStopTime_s - ...
                plan.interceptTime_s;
            regularTrackingSampleCount = floor( ...
                trackingDuration_s / options.TrackingSampleTime_s);
            lastRegularTrackingTime_s = plan.interceptTime_s + ...
                regularTrackingSampleCount * options.TrackingSampleTime_s;
            endpointSampleNeeded = regularTrackingSampleCount == 0 || ...
                lastRegularTrackingTime_s < trackingStopTime_s - 1e-9;
            trackingSampleCount = regularTrackingSampleCount + ...
                double(endpointSampleNeeded);
            % Construct a fixed-size vector because this block sits inside
            % the interception-attempt loop. The exact endpoint replaces
            % the final nominal step when the duration is not divisible.
            trackingTime_s = plan.interceptTime_s + ...
                (1:trackingSampleCount).' * options.TrackingSampleTime_s;
            trackingTime_s(end) = trackingStopTime_s;
            trackingPositionUnwrapped_deg = interp1( ...
                target.time_s, target.positionUnwrapped_deg, ...
                trackingTime_s, "linear");
            targetAtInterceptUnwrapped_deg = interp1( ...
                target.time_s, target.positionUnwrapped_deg, ...
                plan.interceptTime_s, "linear");
            azimuthAlignmentOffset_deg = plan.positionUnwrapped_deg(end, 1) - ...
                targetAtInterceptUnwrapped_deg(1);
            trackingPositionUnwrapped_deg(:, 1) = trackingPositionUnwrapped_deg( ...
                :, 1) + ...
                azimuthAlignmentOffset_deg;
            trackingPosition_deg = canonicalPosition( ...
                trackingPositionUnwrapped_deg, limits, options);
            trackingVelocity_deg_s = interp1( ...
                target.time_s, target.velocity_deg_s, ...
                trackingTime_s, "linear");
            trackingAcceleration_deg_s2 = interp1( ...
                target.time_s, target.acceleration_deg_s2, ...
                trackingTime_s, "linear");

            minimumTrackingElevation_deg = limits.elevation_deg(1) - 1e-9;
            maximumTrackingElevation_deg = limits.elevation_deg(2) + 1e-9;
            aboveMinimumTrackingElevation = trackingPosition_deg(:, 2) >= minimumTrackingElevation_deg;
            belowMaximumTrackingElevation = trackingPosition_deg(:, 2) <= maximumTrackingElevation_deg;
            trackingInsideLimits = aboveMinimumTrackingElevation & ...
                belowMaximumTrackingElevation;
            if ~allowAzimuthWrap
                minimumTrackingAzimuth_deg = limits.azimuth_deg(1) - 1e-9;
                maximumTrackingAzimuth_deg = limits.azimuth_deg(2) + 1e-9;
                aboveMinimumTrackingAzimuth = trackingPosition_deg(:, 1) >= minimumTrackingAzimuth_deg;
                belowMaximumTrackingAzimuth = trackingPosition_deg(:, 1) <= maximumTrackingAzimuth_deg;
                trackingInsideLimits = trackingInsideLimits & ...
                    aboveMinimumTrackingAzimuth & ...
                    belowMaximumTrackingAzimuth;
            end
            maximumTrackingVelocity_deg_s = limits.maxVelocity_deg_s + 1e-9;
            maximumTrackingAcceleration_deg_s2 = limits.maxAcceleration_deg_s2 + 1e-9;
            velocityInsideLimits = abs(trackingVelocity_deg_s) <= maximumTrackingVelocity_deg_s;
            accelerationInsideLimits = abs(trackingAcceleration_deg_s2) <= maximumTrackingAcceleration_deg_s2;
            trackingDynamicsValid = all(velocityInsideLimits, 2) & ...
                all(accelerationInsideLimits, 2);
            trackingBlocked = queryAzElTimeObstacle(workspace, ...
                trackingPosition_deg(:, 1), ...
                trackingPosition_deg(:, 2), trackingTime_s, struct( ...
                "SafetyMarginDeg", options.SafetyMargin_deg, ...
                "TimePaddingSamples", plan.options.TimePaddingSamples));
            trackingSafe = trackingInsideLimits & ...
                trackingDynamicsValid & ~trackingBlocked;
            % The first unsafe sample diagnoses termination but never enters
            % the command history.
            firstUnsafeTrackingIndex = find(~trackingSafe, 1);
            if isempty(firstUnsafeTrackingIndex)
                retainedTrackingIndices = (1:numel(trackingTime_s)).';
                trackingTerminationReason = "trackingWindowComplete";
            elseif firstUnsafeTrackingIndex == 1
                retainedTrackingIndices = zeros(0, 1);
                trackingTerminationReason = trackingFailureReason( ...
                    trackingBlocked(firstUnsafeTrackingIndex), ...
                    trackingInsideLimits(firstUnsafeTrackingIndex), ...
                    trackingDynamicsValid(firstUnsafeTrackingIndex));
            else
                retainedTrackingIndices = ( ...
                    1:firstUnsafeTrackingIndex - 1).';
                trackingTerminationReason = trackingFailureReason( ...
                    trackingBlocked(firstUnsafeTrackingIndex), ...
                    trackingInsideLimits(firstUnsafeTrackingIndex), ...
                    trackingDynamicsValid(firstUnsafeTrackingIndex));
            end

            if ~isempty(retainedTrackingIndices)
                previousPositionUnwrapped_deg = plan.positionUnwrapped_deg( ...
                    end, :);
                appendedPositionUnwrapped_deg = [ ...
                    previousPositionUnwrapped_deg; ...
                    trackingPositionUnwrapped_deg( ...
                    retainedTrackingIndices, :)];
                plan.angularPathLength_deg = plan.angularPathLength_deg + ...
                    sum(hypot( ...
                    diff(appendedPositionUnwrapped_deg(:, 1)), ...
                    diff(appendedPositionUnwrapped_deg(:, 2))));
                plan.time_s = [ ...
                    plan.time_s; trackingTime_s(retainedTrackingIndices)];
                plan.position_deg = [plan.position_deg; ...
                    trackingPosition_deg(retainedTrackingIndices, :)];
                plan.positionUnwrapped_deg = [ ...
                    plan.positionUnwrapped_deg; ...
                    trackingPositionUnwrapped_deg( ...
                    retainedTrackingIndices, :)];
                plan.velocity_deg_s = [ ...
                    plan.velocity_deg_s; ...
                    trackingVelocity_deg_s(retainedTrackingIndices, :)];
                plan.acceleration_deg_s2 = [ ...
                    plan.acceleration_deg_s2; ...
                    trackingAcceleration_deg_s2( ...
                    retainedTrackingIndices, :)];
                plan.isWaiting = [plan.isWaiting; ...
                    false(numel(retainedTrackingIndices), 1)];
                plan.trackingSuccess = true;
                plan.trackingTime_s = trackingTime_s( ...
                    retainedTrackingIndices);
                plan.trackingPosition_deg = trackingPosition_deg( ...
                    retainedTrackingIndices, :);
                plan.trackingVelocity_deg_s = trackingVelocity_deg_s( ...
                    retainedTrackingIndices, :);
                plan.trackingAcceleration_deg_s2 = trackingAcceleration_deg_s2( ...
                    retainedTrackingIndices, :);
                plan.trackingEndTime_s = trackingTime_s( ...
                    retainedTrackingIndices(end));
            end
            plan.cost_s = plan.time_s(end) - plan.time_s(1);
            plan.trackingTerminationReason = trackingTerminationReason;
            plan.trackingTerminatedByObstacle = trackingTerminationReason == "obstacle";
            plan.commandEndState = struct( ...
                "time_s", plan.time_s(end), ...
                "position_deg", plan.position_deg(end, :), ...
                "velocity_deg_s", plan.velocity_deg_s(end, :), ...
                "acceleration_deg_s2", ...
                plan.acceleration_deg_s2(end, :));
        end
    end
    return;
end

plan = struct( ...
    "success", false, ...
    "interceptSuccess", false, ...
    "message", "No sampled moving-target interception was found.", ...
    "time_s", zeros(0, 1), ...
    "position_deg", zeros(0, 2), ...
    "workspace", workspace, ...
    "startState", initialState, ...
    "targetTrajectory", target, ...
    "limits", limits, ...
    "options", options, ...
    "interceptAttempts", attempts(1:attemptCount), ...
    "interceptCandidateCount", nnz(eligible), ...
    "interceptFilter", struct( ...
        "sampleCount", numel(candidateTime), ...
        "insideLimitCount", nnz(inside), ...
        "safeCount", nnz(inside & ~blocked), ...
        "reachableCount", nnz(inside & ~blocked & reachable), ...
        "eligibleCount", nnz(eligible)), ...
    "interceptSearchElapsed_s", toc(timer));
plan = finalizeAzElPlanFailure(plan);
end

function values = normalizeTargetSamples(values, sampleCount, name)
% Supplied velocity and acceleration arrays share this shape contract.
validateattributes(values, {'numeric'}, ...
    {'2d', 'nrows', sampleCount, 'ncols', 2, ...
    'real', 'finite'}, mfilename, name);
values = double(values);
end

function derivative = sampledDerivative(values, time_s)
% Position and velocity differentiation must use identical endpoint and
% centered-difference conventions.
derivative = zeros(size(values));
sampleCount = numel(time_s);
if sampleCount == 1
    return;
end
derivative(1, :) = (values(2, :) - values(1, :)) / ...
    (time_s(2) - time_s(1));
derivative(end, :) = (values(end, :) - values(end - 1, :)) / ...
    (time_s(end) - time_s(end - 1));
if sampleCount > 2
    % Centered differences reduce phase bias for interior target samples.
    duration = time_s(3:end) - time_s(1:end - 2);
    derivative(2:end - 1, :) = ( ...
        values(3:end, :) - values(1:end - 2, :)) ./ duration;
end
end

function position = canonicalPosition(position, limits, options)
% Candidate filtering, catch validation, and tracking must use one azimuth
% interval while preserving a separate unwrapped derivative history.
allowWrap = fieldOr(options, "AllowAzimuthWrap", ...
    diff(limits.azimuth_deg) >= 360 - 1e-9);
if allowWrap
    span = diff(limits.azimuth_deg);
    position(:, 1) = mod( ...
        position(:, 1) - limits.azimuth_deg(1), span) + ...
        limits.azimuth_deg(1);
end
end

function reason = trackingFailureReason(blocked, inside, dynamicsValid)
% Both first-sample and later tracking failures use the same diagnostic
% precedence so obstacle termination cannot be misreported.
if blocked
    reason = "obstacle";
elseif ~inside
    reason = "outsidePointingLimits";
elseif ~dynamicsValid
    reason = "targetExceedsDynamicLimits";
else
    reason = "trackingStopped";
end
end

function value = fieldOr(input, name, fallback)
% Optional planner and target controls share one empty-as-missing policy.
if isfield(input, name) && ~isempty(input.(name))
    value = input.(name);
else
    value = fallback;
end
end
